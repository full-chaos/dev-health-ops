func render(v semver) string {
	pre, num := "-", "-"
	if v.preType != "" {
		pre, num = v.preType, v.preNum.String()
	}
	return fmt.Sprintf("%s.%s.%s.%s.%s", v.major, v.minor, v.patch, pre, num)
}

func TestParseSemverMatchesRecordedPython(t *testing.T) {
	for _, row := range parseSemverRows {
		v, ok, err := parseSemver(row.in)
		if err != nil {
			t.Errorf("%q: %v", row.in, err)
			continue
		}
		got := ""
		if ok {
			got = render(v)
		}
		if got != row.want {
			t.Errorf("%q: got %q, Python %q", row.in, got, row.want)
		}
	}
}

