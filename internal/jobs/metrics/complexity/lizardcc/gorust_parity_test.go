// narrower half) -- this is the generic check that would have caught the
// missing Rust `where` fixture (now added, testdata/corpus_go_rust/
// where_clause.rs.txt) without needing a codex round to spot it by hand.
// goConditions and rustConditions are asserted separately since a keyword
// unique to one language (e.g. Rust's "where") legitimately never appears
// in the other's fixtures.
