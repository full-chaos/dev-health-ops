func TestParseSemverRefusesMoreThan4300Digits(t *testing.T) {
	for _, in := range []string{
		strings.Repeat("9", 4301) + ".0.0",
		"0." + strings.Repeat("9", 4301) + ".0",
		"0.0." + strings.Repeat("9", 4301),
		"0.0.0-beta." + strings.Repeat("9", 4301),
	} {
		if _, ok, err := parseSemver(in); err == nil || ok {
			t.Errorf("%.20s...: err %v, ok %v; want the int() ValueError", in, err, ok)
		}
	}
	if _, ok, err := parseSemver(strings.Repeat("9", 4300) + ".0.0"); err != nil || !ok {
		t.Errorf("4300 digits: err %v, ok %v; want a version", err, ok)
	}
}

func TestIncrementedRefusesAnIntegerStrOverTheLimit(t *testing.T) {
	nines := new(big.Int)
	nines.SetString(strings.Repeat("9", 4300), 10)
	one := big.NewInt(1)
	if _, err := incremented(semver{major: one, minor: one, patch: nines}, "beta"); err == nil {
		t.Error("patch + 1 of 4300 nines is 4301 digits: want the ValueError of str()")
	}
	if _, err := incremented(semver{major: one, minor: one, patch: one, preType: "beta", preNum: nines}, "beta"); err == nil {
		t.Error("pre_num + 1 of 4300 nines is 4301 digits: want the ValueError of str()")
	}
	short := new(big.Int)
	short.SetString(strings.Repeat("9", 4299), 10)
	if got, err := incremented(semver{major: one, minor: one, patch: short}, "beta"); err != nil || !strings.HasSuffix(got, "-beta.1") {
		t.Errorf("4299 nines + 1: %q, %v; want a tag", got, err)
	}
}

func TestIncrementedWritesNormalisedIntegers(t *testing.T) {
	v, ok, err := parseSemver("٠١.٠٠٢.٠٠٣")
	if err != nil || !ok {
		t.Fatal(err)
	}
	got, err := incremented(v, "rc")
	if err != nil || got != "1.2.4-rc.1" {
		t.Errorf("got %q, %v; want 1.2.4-rc.1", got, err)
	}
}
