// Command credrefgen renders the public credential reference from the auth registry and docs data.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const (
	registryPath  = "contracts/auth/v1/credential-classes.json"
	referencePath = "docs-data/auth/credential-reference.json"
	pagePath      = "docs/reference/auth/credential-reference.md"
)

type registry struct {
	Classes []credentialClass `json:"classes"`
}

type credentialClass struct {
	ID      string `json:"class_id"`
	Status  string `json:"status"`
	Markers []struct {
		Kind  string `json:"kind"`
		Name  string `json:"name"`
		Shape string `json:"shape"`
	} `json:"markers"`
}

// Public summaries are maintained independently of the runtime contract.
type publicReference struct {
	Description string `json:"description"`
	Issuer      string `json:"issuer"`
	Acceptors   string `json:"acceptors"`
	Format      string `json:"format"`
	Storage     string `json:"storage"`
	Lifecycle   string `json:"lifecycle"`
}

var privateText = regexp.MustCompile(`(?i)CHAOS-|\b(?:D[0-9]+|W[0-9]+|fcdev|acp|pm|lane|agent)\b`)

// render is shared by the command and the committed-file freshness test.
func render(raw, referenceRaw []byte) ([]byte, error) {
	var inventory registry
	if err := json.Unmarshal(raw, &inventory); err != nil {
		return nil, fmt.Errorf("read credential registry: %w", err)
	}
	if len(inventory.Classes) == 0 {
		return nil, fmt.Errorf("credential registry is empty")
	}
	var references map[string]publicReference
	if err := json.Unmarshal(referenceRaw, &references); err != nil {
		return nil, fmt.Errorf("read credential reference data: %w", err)
	}
	seen := make(map[string]bool)
	for _, class := range inventory.Classes {
		if class.ID == "" || seen[class.ID] {
			return nil, fmt.Errorf("empty or duplicate credential class id: %q", class.ID)
		}
		seen[class.ID] = true
		if _, ok := references[class.ID]; !ok {
			return nil, fmt.Errorf("contract class %q has no docs row in %s", class.ID, referencePath)
		}
	}
	for id := range references {
		if !seen[id] {
			return nil, fmt.Errorf("docs row %q in %s names no contract class", id, referencePath)
		}
	}
	sort.Slice(inventory.Classes, func(i, j int) bool { return inventory.Classes[i].ID < inventory.Classes[j].ID })
	var out bytes.Buffer
	out.WriteString(`---
page_id: ref-auth-credential-reference
summary: Credential issuers, acceptors, formats, storage and lifetimes.
content_type: reference
owner: platform-operations
source_of_truth:
  - contracts/auth/v1/credential-classes.json
  - docs-data/auth/credential-reference.json
applicability: current
lifecycle: active
---

<!-- Generated by go run ./cmd/credrefgen from contracts/auth/v1/credential-classes.json and docs-data/auth/credential-reference.json. DO NOT EDIT. -->

# Credential reference

This table lists every credential class in the registry. Live means the class is not retired.
It does not mean every deployment enables it or that an endpoint accepts it.
The acceptor column states where it is used. A context header is not proof of identity.

Regenerate this page from the repository root with ` + "`go run ./cmd/credrefgen`" + `.
Update the public summaries in ` + "`docs-data/auth/credential-reference.json`" + ` when behavior changes.
See the [auth architecture](../../operate/architecture/auth-control-plane.md) for the request path.

| Class id | What it is | Issuer | Accepted by | Format and markers | Storage | Rotation and expiry | Status |
| --- | --- | --- | --- | --- | --- | --- | --- |
`)
	for _, class := range inventory.Classes {
		status := "live"
		switch class.Status {
		case "retired":
			status = "retired"
		case "active", "unconsumed", "optional_feature", "legacy_permissive":
		default:
			return nil, fmt.Errorf("class %s has unknown status %q", class.ID, class.Status)
		}
		p := references[class.ID]
		for _, value := range []string{p.Description, p.Issuer, p.Acceptors, p.Format, p.Storage, p.Lifecycle} {
			if strings.TrimSpace(value) == "" {
				return nil, fmt.Errorf("class %s needs all public reference fields in %s", class.ID, referencePath)
			}
		}
		format := p.Format
		for _, marker := range class.Markers {
			format += "; " + marker.Kind + "=" + marker.Name
			if marker.Shape != "" {
				format += " (" + marker.Shape + ")"
			}
		}
		cells := []string{"`" + class.ID + "`", p.Description, p.Issuer, p.Acceptors, format, p.Storage, p.Lifecycle, status}
		for i, cell := range cells {
			if privateText.MatchString(cell) {
				return nil, fmt.Errorf("class %s contains non-public text", class.ID)
			}
			cells[i] = markdownCell(cell)
		}
		fmt.Fprintf(&out, "| %s |\n", strings.Join(cells, " | "))
	}
	return out.Bytes(), nil
}

func markdownCell(s string) string {
	s = strings.ReplaceAll(s, "&", "&amp;")
	s = strings.ReplaceAll(s, "<", "&lt;")
	s = strings.ReplaceAll(s, ">", "&gt;")
	s = strings.ReplaceAll(s, "|", "&#124;")
	return strings.Join(strings.Fields(s), " ")
}

func generate(root string) error {
	raw, err := os.ReadFile(filepath.Join(root, registryPath))
	if err != nil {
		return err
	}
	referenceRaw, err := os.ReadFile(filepath.Join(root, referencePath))
	if err != nil {
		return err
	}
	page, err := render(raw, referenceRaw)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(root, pagePath), page, 0o644)
}

func main() {
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	if err := generate(*root); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
