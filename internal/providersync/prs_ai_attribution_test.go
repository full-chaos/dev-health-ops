func TestPRAttributionSinkFencesRowsToTheUnitProvider(t *testing.T) {
	t.Parallel()
	batch, _ := prAttributionPRsEffect(t)
	var effect EffectBatch
	for _, candidate := range batch.Effects {
		if candidate.Destination == "ai_attribution" {
			effect = candidate
		}
	}
	lease := providerfoundation.LeaseGuardFunc(func(context.Context) error { return nil })
	claim := prAttributionClaim("github", "prs")
	if err := (GitHubPullRequestSocialClickHouseEffects{Lease: lease}).WriteEffect(
		context.Background(), claim, effect,
	); !errors.Is(err, ErrInvalidConfiguration) {
		// A real connection is required once rows exist; the fence accepted
		// the effect and the adapter reached its connection guard.
		t.Fatalf("github rows through the github sink: err=%v want the connection guard", err)
	}
	gitlabClaim := prAttributionClaim("gitlab", "prs")
	gitlabEffect := effect
	gitlabEffect.Rows = append([]json.RawMessage(nil), effect.Rows...)
	for index, raw := range gitlabEffect.Rows {
		gitlabEffect.Rows[index] = json.RawMessage(strings.Replace(string(raw), `"provider":"github"`, `"provider":"gitlab"`, 1))
	}
	rebuilt, err := BuildEffectBatch("ai_attribution", EffectReadbackRequired, gitlabEffect.Rows)
	if err != nil {
		t.Fatal(err)
	}
	// github rows inside a gitlab unit, and gitlab rows inside a github unit,
	// are refused before any connection is touched.
	if _, err := newPRAIAttributionEffectIdentity(gitlabClaim, effect); !errors.Is(err, ErrInvalidConfiguration) {
		t.Fatalf("github rows in a gitlab unit: err=%v", err)
	}
	if _, err := newPRAIAttributionEffectIdentity(claim, rebuilt); !errors.Is(err, ErrInvalidConfiguration) {
		t.Fatalf("gitlab rows in a github unit: err=%v", err)
	}
	if _, err := newPRAIAttributionEffectIdentity(claim, effect); err != nil {
		t.Fatalf("github rows in a github unit: %v", err)
	}
	var wrongSubject []json.RawMessage
	for _, raw := range effect.Rows {
		wrongSubject = append(wrongSubject, json.RawMessage(strings.Replace(
			string(raw), `"subject_type":"pull_request"`, `"subject_type":"issue"`, 1)))
	}
	issueEffect, err := BuildEffectBatch("ai_attribution", EffectReadbackRequired, wrongSubject)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := newPRAIAttributionEffectIdentity(claim, issueEffect); !errors.Is(err, ErrInvalidConfiguration) {
		t.Fatalf("an issue-subject row in a PR-social unit: err=%v", err)
	}
	tampered := effect
	tampered.Rows = append(append([]json.RawMessage(nil), effect.Rows...), effect.Rows[0])
	if _, err := newPRAIAttributionEffectIdentity(claim, tampered); !errors.Is(err, ErrInvalidConfiguration) {
		t.Fatalf("rows that no longer match the effect digest: err=%v", err)
	}
	workItemsClaim := prAttributionClaim("github", "work-items")
	if _, err := newPRAIAttributionEffectIdentity(workItemsClaim, effect); !errors.Is(err, ErrInvalidConfiguration) {
		t.Fatalf("a work-items unit is not a PR-social unit: err=%v", err)
	}
	bogus := claim
	bogus.Provider = "jira"
	if _, err := newPRAIAttributionEffectIdentity(bogus, effect); !errors.Is(err, ErrInvalidConfiguration) {
		t.Fatalf("a jira unit must not write pull request attribution: err=%v", err)
	}
}

