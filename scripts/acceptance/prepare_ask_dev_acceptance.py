#!/usr/bin/env python3
"""Seed the Ask Dev entitlement state and certify the acceptance provider.

The data fixture itself is generated by ``dev-hops fixtures generate`` in the
Compose launcher. This script deliberately uses only public HTTP endpoints for
authentication, feature overrides, readiness, and capability verification.
"""

from __future__ import annotations

import json
import os
import sys
from typing import Any
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

_REQUIRED_FEATURES = (
    "ask_dev",
    "ask_dev_contextual_entrypoints",
)
_DEFAULT_EXPECTED_MODEL = "ask-dev-scripted-v1"


class AcceptanceFailure(RuntimeError):
    """A deterministic acceptance prerequisite was not established."""


class AcceptanceApi:
    def __init__(self, base_url: str) -> None:
        self.base_url = base_url.rstrip("/")
        self.token: str | None = None

    def request(
        self,
        method: str,
        path: str,
        payload: dict[str, Any] | None = None,
    ) -> Any:
        body = None
        headers = {"Accept": "application/json"}
        if payload is not None:
            body = json.dumps(payload, separators=(",", ":")).encode()
            headers["Content-Type"] = "application/json"
        if self.token:
            headers["Authorization"] = f"Bearer {self.token}"
        request = Request(
            f"{self.base_url}{path}",
            data=body,
            headers=headers,
            method=method,
        )
        try:
            with urlopen(request, timeout=20) as response:  # noqa: S310
                response_body = response.read()
        except HTTPError as exc:
            detail = exc.read().decode(errors="replace")
            raise AcceptanceFailure(
                f"{method} {path} returned HTTP {exc.code}: {detail}"
            ) from exc
        except URLError as exc:
            raise AcceptanceFailure(f"{method} {path} failed: {exc.reason}") from exc
        if not response_body:
            return None
        try:
            return json.loads(response_body)
        except json.JSONDecodeError as exc:
            raise AcceptanceFailure(
                f"{method} {path} returned non-JSON content"
            ) from exc


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise AcceptanceFailure(message)


def prepare(
    api: AcceptanceApi,
    *,
    email: str,
    password: str,
    expected_model: str = _DEFAULT_EXPECTED_MODEL,
) -> str:
    login = api.request(
        "POST",
        "/api/v1/auth/login",
        {"email": email, "password": password},
    )
    _require(isinstance(login, dict), "login response was not an object")
    token = login.get("access_token")
    user = login.get("user")
    _require(isinstance(token, str) and bool(token), "login returned no access token")
    _require(isinstance(user, dict), "login returned no user")
    _require(user.get("is_superuser") is True, "acceptance user is not a superuser")
    org_id = user.get("org_id")
    _require(isinstance(org_id, str) and bool(org_id), "login returned no org_id")
    api.token = token

    flags = api.request("GET", "/api/v1/admin/feature-flags")
    _require(isinstance(flags, list), "feature flag response was not a list")
    flags_by_key = {item.get("key"): item for item in flags if isinstance(item, dict)}
    missing = [key for key in _REQUIRED_FEATURES if key not in flags_by_key]
    _require(not missing, f"required feature flags are missing: {', '.join(missing)}")
    disabled = [
        key
        for key in _REQUIRED_FEATURES
        if flags_by_key[key].get("is_enabled") is not True
    ]
    _require(
        not disabled,
        f"required feature flags are globally disabled: {', '.join(disabled)}",
    )

    override_path = f"/api/v1/admin/orgs/{org_id}/feature-overrides"
    overrides = api.request("GET", override_path)
    _require(isinstance(overrides, list), "feature override response was not a list")
    overrides_by_key = {
        item.get("feature_key"): item for item in overrides if isinstance(item, dict)
    }
    for key in _REQUIRED_FEATURES:
        existing = overrides_by_key.get(key)
        if existing is None:
            created = api.request(
                "POST",
                override_path,
                {
                    "feature_id": flags_by_key[key]["id"],
                    "is_enabled": True,
                    "reason": "Ask Dev deterministic Compose acceptance",
                },
            )
            _require(
                isinstance(created, dict) and created.get("is_enabled") is True,
                f"failed to enable {key}",
            )
        elif existing.get("is_enabled") is not True:
            override_id = existing.get("id")
            _require(isinstance(override_id, str), f"{key} override has no id")
            updated = api.request(
                "PATCH",
                f"{override_path}/{override_id}",
                {
                    "is_enabled": True,
                    "reason": "Ask Dev deterministic Compose acceptance",
                },
            )
            _require(
                isinstance(updated, dict) and updated.get("is_enabled") is True,
                f"failed to enable {key}",
            )

    readiness = api.request("POST", "/api/v1/admin/ask-dev/readiness", {})
    _require(isinstance(readiness, dict), "readiness response was not an object")
    expected_readiness = {
        "ask_dev_enabled": True,
        "chat_window_available": True,
        "full_page_available": True,
        "provider_source": "platform",
        "readiness": "ready",
        "effective_model_label": expected_model,
    }
    for field, expected in expected_readiness.items():
        _require(
            readiness.get(field) == expected,
            f"readiness {field} was {readiness.get(field)!r}, expected {expected!r}",
        )
    _require(
        bool(readiness.get("readiness_checked_at")),
        "readiness did not persist a checked-at timestamp",
    )

    capabilities = api.request("GET", "/api/v1/dev/capabilities")
    _require(isinstance(capabilities, dict), "capabilities response was not an object")
    expected_capabilities = {
        "ask_dev": True,
        "agent_context_runtime": False,
        "can_read": True,
        "can_manage": True,
        "contextual_entrypoints": True,
        "evidence_resolver": True,
        "provider_source": "platform",
        "readiness": "ready",
        "effective_model_label": expected_model,
    }
    for field, expected in expected_capabilities.items():
        _require(
            capabilities.get(field) == expected,
            f"capability {field} was {capabilities.get(field)!r}, expected {expected!r}",
        )
    return org_id


def main() -> int:
    if os.getenv("ASK_DEV_LIVE_ACCEPTANCE") != "1":
        print("ASK_DEV_LIVE_ACCEPTANCE=1 is required", file=sys.stderr)
        return 64
    api = AcceptanceApi(
        os.getenv("ASK_DEV_ACCEPTANCE_API_URL", "http://127.0.0.1:8000")
    )
    email = os.getenv("TEST_SUPERUSER_EMAIL", "admin@devhealth.example")
    password = os.getenv("TEST_SUPERUSER_PASSWORD", "devhealth123")
    expected_model = os.getenv(
        "ASK_DEV_ACCEPTANCE_EXPECTED_MODEL", _DEFAULT_EXPECTED_MODEL
    ).strip()
    if not expected_model:
        print("ASK_DEV_ACCEPTANCE_EXPECTED_MODEL must not be empty", file=sys.stderr)
        return 64
    try:
        org_id = prepare(
            api,
            email=email,
            password=password,
            expected_model=expected_model,
        )
    except AcceptanceFailure as exc:
        print(f"Ask Dev acceptance preparation failed: {exc}", file=sys.stderr)
        return 1
    print(f"Ask Dev acceptance readiness established for organization {org_id}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
