// TestGitHubPRsRouteAttributionEqualsWorkItemsRouteRowForRow pins the one
// invariant the two writers share: both routes write the same ai_attribution
// key, and the last writer wins, so they must never disagree. Both rows come
// from the real collectors fed the same /pulls/{n} bodies, through the real
// normalizers of each route.
func TestGitHubPRsRouteAttributionEqualsWorkItemsRouteRowForRow(t *testing.T) {
	t.Parallel()
	batch, _ := prAttributionPRsEffect(t)
	fromPRs := sortedAttributions(attributionEffectRows(t, batch))
	fromWorkItems := sortedAttributions(prAttributionWorkItemsRows(t))
	sources := map[string]bool{}
	subjects := map[string]bool{}
	for _, row := range fromWorkItems {
		sources[row.Source] = true
		subjects[row.SubjectID] = true
	}
	// Every detector input must be exercised by the fixture, or equality
	// proves nothing about it: label, author kind, trailer, branch, body text.
	for _, source := range []string{"pr_label", "bot_author", "commit_trailer", "branch_name", "pr_body"} {
		if !sources[source] {
			t.Fatalf("fixture never exercises source %s: %v", source, sources)
		}
	}
	if subjects["54"] || !subjects["52"] || !subjects["53"] {
		t.Fatalf("subjects=%v want 52 and 53 only", subjects)
	}
	// Compared as the bytes each route hands its effect: the prs rows crossed
	// an effect round trip, the work-items rows did not, and typed nils inside
	// the evidence map differ in memory but not on the wire.
	prsJSON, _ := json.Marshal(fromPRs)
	itemsJSON, _ := json.Marshal(fromWorkItems)
	if string(prsJSON) != string(itemsJSON) {
		at := 0
		for at < len(prsJSON) && at < len(itemsJSON) && prsJSON[at] == itemsJSON[at] {
			at++
		}
		lo := max(at-120, 0)
		t.Fatalf("prs route rows differ from work-items route rows at byte %d\nprs:   ...%s\nitems: ...%s",
			at, prsJSON[lo:min(at+160, len(prsJSON))], itemsJSON[lo:min(at+160, len(itemsJSON))])
	}
}

