func sortedAttributions(rows []githubAIAttributionRow) []githubAIAttributionRow {
	out := append([]githubAIAttributionRow(nil), rows...)
	sort.Slice(out, func(left, right int) bool {
		if out[left].SubjectID != out[right].SubjectID {
			return out[left].SubjectID < out[right].SubjectID
		}
		if out[left].Source != out[right].Source {
			return out[left].Source < out[right].Source
		}
		return out[left].RecordID.String() < out[right].RecordID.String()
	})
	return out
}

