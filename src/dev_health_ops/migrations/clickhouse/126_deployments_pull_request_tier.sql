-- CHAOS-9610: store which rule matched a deployment's pull request link, beside
-- pull_request_number, so a reader can tell an exact link from a guess.
-- pull_request_tier is one of
--   exact_merge_sha  GitHub: a merged pull request whose merge_commit_sha is the deployed sha
--   merged_pr        GitHub and GitLab: the first merged pull or merge request listed for the sha
--   first_listed     GitHub: no merged pull request, so the first one listed
--   pushed           the number was asserted by a pushed (ingest) deployment, no provider rule ran
-- and '' when the row has no link. Additive: a row written before this column
-- reads '' (tier unknown, even when it has a number) until the next sync of its
-- unit rewrites it; no backfill is run.
ALTER TABLE deployments ADD COLUMN IF NOT EXISTS pull_request_tier LowCardinality(String) DEFAULT '' AFTER pull_request_number;
