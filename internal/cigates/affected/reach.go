// reach.tsv (generated): package<TAB>site<TAB>reacher. A code-scope site of dynreads.tsv, of an unexpressed walk or of an
// unexpressed edge runs only in a program that can call it. Each row names one package whose test binary, or whose
// main program, reaches a function that holds the site (Rapid Type Analysis from the generated test main and from
// main, each with its package init, over every tag set in reachTags). reacher `-`: no program reaches the site;
// reacher `*`: the site is in no function the analysis can place (a package variable initializer, a file no tag set
// builds), so every test binary that links the package is selected, as without the table. plan-verdict selects the
// reachers of a code-scope row instead of its reverse import closure. A code-scope row with no reach.tsv row is a
// defect of the tables (FULL); `cigate plan-reads --reach` recomputes the table and fails on any difference.
const (
	reachFile = "reach.tsv"
	reachAny  = "*"
	reachNone = "-"
)

// reachTags: the build tag sets of the planned test runs (the integration plan, and its race legs). An untagged build
// (the go-quality legs) is a subset of the integration build, so its programs reach no more: no file is built only
// without the integration tag (scan.go refuses one). The first set loads the whole module. A further set reloads only the packages with a _test.go file constrained by a tag it adds (their
// test binaries are the only programs that change), or the whole module when a non-test file is.
var reachTags = [][]string{{"integration"}, {"integration", "race"}}

var buildLine = regexp.MustCompile(`(?m)^//go:build (.*)$`)

// tagDirs is the package directories whose _test.go files name one of tags in a build constraint, and whether a
// non-test file does.
func tagDirs(root string, tags []string) ([]string, bool, error) {
	files, err := goSources(root, repoFiles(root))
	if err != nil {
		return nil, false, err
	}
	dirs := map[string]bool{}
	for _, f := range files {
		src, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(f)))
		if err != nil {
			return nil, false, err
		}
		m := buildLine.FindSubmatch(src)
		if m == nil {
			continue
		}
		words := strings.FieldsFunc(string(m[1]), func(r rune) bool { return !(r == '_' || r == '.' || unicode.IsLetter(r) || unicode.IsDigit(r)) })
		for _, w := range words {
			if !slices.Contains(tags, w) {
				continue
			}
			if !strings.HasSuffix(f, "_test.go") {
				return nil, true, nil
			}
			dirs[path.Dir(f)] = true
		}
	}
	return sortedKeys(dirs), false, nil
}

var reachHeader = "# GENERATED by `cigate plan-reads --root . --write` (reach.go): package<TAB>site<TAB>reacher\n"

// codeSites groups the code-scope reads the tool cannot bound by package<TAB>site.
func codeSites(reads []Read) map[string][]Read {
	out := map[string][]Read{}
	for _, r := range reads {
		if r.Test {
			continue
		}
		switch {
		case r.Kind == ReadDyn, r.Kind == ReadWalk && r.Root == unexpressed, r.Kind == ReadEdge && r.Target == unexpressed:
			k := r.Package + "\t" + path.Base(r.File)
			out[k] = append(out[k], r)
		}
	}
	return out
}

// reachStats is what one reach computation cost.
type reachStats struct {
	sites, programs int
	wall            time.Duration
	peakRSSMiB      int64
}

// reachRows computes the reach.tsv rows of the code-scope sites of reads under root.
func reachRows(root string, reads []Read) (map[string]bool, reachStats, error) {
	start := time.Now()
	sites := codeSites(reads)
	rows := map[string]bool{}
	st := reachStats{sites: len(sites)}
	if len(sites) == 0 {
		return rows, st, nil
	}
	module := modulePath(root)
	if module == "" {
		return nil, st, errors.New("reach: no module path in go.mod")
	}
	realRoot, err := filepath.EvalSymlinks(root)
	if err != nil {
		return nil, st, err
	}
	reachers := map[string]map[string]bool{} // site key -> reacher dirs
	placed := map[string]bool{}              // site key -> every read of the site is in a function of some tag set
	for i, tags := range reachTags {
		var only []string
		if i > 0 {
			dirs, all, err := tagDirs(realRoot, slices.DeleteFunc(slices.Clone(tags), func(t string) bool { return slices.Contains(reachTags[0], t) }))
			if err != nil {
				return nil, st, err
			}
			if !all {
				if len(dirs) == 0 {
					continue
				}
				only = dirs
			}
		}
		n, err := reachOnce(realRoot, module, tags, only, sites, reachers, placed)
		if err != nil {
			return nil, st, err
		}
		st.programs += n
	}
	for k := range sites {
		switch {
		case !placed[k]:
			rows[k+"\t"+reachAny] = true
		case len(reachers[k]) == 0:
			rows[k+"\t"+reachNone] = true
		default:
			for r := range reachers[k] {
				rows[k+"\t"+r] = true
			}
		}
	}
	st.wall = time.Since(start)
	st.peakRSSMiB = peakRSSMiB()
	return rows, st, nil
}

// reachOnce loads the module with one tag set and records the programs that reach each site. A site is placed when
// every read of it lies inside a function of this build.
func reachOnce(root, module string, tags, only []string, sites map[string][]Read, reachers map[string]map[string]bool, placed map[string]bool) (int, error) {
	cfg := &packages.Config{Mode: packages.LoadAllSyntax, Tests: true, Dir: root, BuildFlags: []string{"-tags=" + strings.Join(tags, ",")}}
	patterns := []string{"./..."}
	if only != nil {
		patterns = nil
		for _, d := range only {
			patterns = append(patterns, "./"+d)
		}
	}
	pkgs, err := packages.Load(cfg, patterns...)
	if err != nil {
		return 0, fmt.Errorf("reach (tags %s): %w", strings.Join(tags, ","), err)
	}
	var loadErrs []string
	packages.Visit(pkgs, nil, func(p *packages.Package) {
		for _, e := range p.Errors {
			loadErrs = append(loadErrs, e.Error())
		}
	})
	if len(loadErrs) > 0 {
		return 0, fmt.Errorf("reach (tags %s): the module does not type-check, so its call graph is unknown: %s", strings.Join(tags, ","), loadErrs[0])
	}
	prog, _ := ssautil.AllPackages(pkgs, ssa.InstantiateGenerics)
	prog.Build()

	// The functions whose source span holds each read of each site.
	type span struct {
		fn         *ssa.Function
		start, end int
	}
	byFile := map[string][]span{}
	rel := map[string]string{}
	for fn := range ssautil.AllFunctions(prog) {
		syn := fn.Syntax()
		if syn == nil {
			continue
		}
		s, e := prog.Fset.Position(syn.Pos()), prog.Fset.Position(syn.End())
		r, ok := rel[s.Filename]
		if !ok {
			r = repoRel(root, s.Filename)
			rel[s.Filename] = r
		}
		if r != "" {
			byFile[r] = append(byFile[r], span{fn, s.Line, e.Line})
		}
	}
	holders := map[string][]*ssa.Function{}
	for k, rs := range sites {
		all := true
		for _, r := range rs {
			found := false
			for _, sp := range byFile[r.File] {
				if sp.start <= r.Line && r.Line <= sp.end {
					holders[k] = append(holders[k], sp.fn)
					found = true
				}
			}
			all = all && found
		}
		if all {
			placed[k] = true
		}
	}

	// One program per generated test main and per main package of the module, each from main and its package init, and
	// the packages it is built from.
	type program struct {
		dir   string
		roots []*ssa.Function
		pkgs  map[*ssa.Package]bool
	}
	var progs []program
	seen := map[string]bool{}
	packages.Visit(pkgs, nil, func(p *packages.Package) {
		if seen[p.ID] || p.Types == nil {
			return
		}
		seen[p.ID] = true
		owner := ""
		switch {
		case strings.HasSuffix(p.ID, ".test") && p.Name == "main":
			owner = strings.TrimSuffix(p.PkgPath, ".test")
		case p.Name == "main" && p.ForTest == "" && !strings.Contains(p.ID, " "):
			owner = p.PkgPath
		default:
			return
		}
		dir, ok := moduleDir(module, owner)
		if !ok || only != nil && !slices.Contains(only, dir) {
			return
		}
		sp := prog.Package(p.Types)
		if sp == nil {
			return
		}
		pr := program{dir: dir, pkgs: map[*ssa.Package]bool{}}
		for _, name := range []string{"main", "init"} {
			if f := sp.Func(name); f != nil {
				pr.roots = append(pr.roots, f)
			}
		}
		packages.Visit([]*packages.Package{p}, nil, func(q *packages.Package) {
			if q.Types != nil {
				if s := prog.Package(q.Types); s != nil {
					pr.pkgs[s] = true
				}
			}
		})
		if len(pr.roots) > 0 {
			progs = append(progs, pr)
		}
	})
	sort.Slice(progs, func(i, j int) bool { return progs[i].dir < progs[j].dir })
	var allRoots []*ssa.Function
	for _, pr := range progs {
		allRoots = append(allRoots, pr.roots...)
	}
	if len(allRoots) == 0 {
		return 0, nil
	}
	g := newReachGraph(prog, allRoots)

	holderIDs := map[string][]int32{}
	for k, fns := range holders {
		for _, fn := range fns {
			if id, ok := g.id[fn]; ok {
				holderIDs[k] = append(holderIDs[k], id)
			}
		}
	}
	var mu sync.Mutex
	work := make(chan program)
	var wg sync.WaitGroup
	for range runtime.GOMAXPROCS(0) {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for pr := range work {
				seen := g.reach(pr.roots, pr.pkgs)
				mu.Lock()
				for k, ids := range holderIDs {
					for _, id := range ids {
						if seen[id] {
							if reachers[k] == nil {
								reachers[k] = map[string]bool{}
							}
							reachers[k][pr.dir] = true
							break
						}
					}
				}
				mu.Unlock()
			}
		}()
	}
	for _, pr := range progs {
		work <- pr
	}
	close(work)
	wg.Wait()
	return len(progs), nil
}

// moduleDir is the repository directory of an import path of the module.
func moduleDir(module, imp string) (string, bool) {
	if imp == module {
		return ".", true
	}
	if d, ok := strings.CutPrefix(imp, module+"/"); ok {
		return d, true
	}
	return "", false
}

// repoRel is file relative to root with forward slashes, "" outside root.
func repoRel(root, file string) string {
	if real, err := filepath.EvalSymlinks(file); err == nil {
		file = real
	}
	r, err := filepath.Rel(root, file)
	if err != nil || r == ".." || strings.HasPrefix(r, ".."+string(filepath.Separator)) {
		return ""
	}
	return filepath.ToSlash(r)
}

func peakRSSMiB() int64 {
	var ru syscall.Rusage
	if err := syscall.Getrusage(syscall.RUSAGE_SELF, &ru); err != nil {
		return 0
	}
	if runtime.GOOS == "darwin" {
		return ru.Maxrss >> 20 // bytes
	}
	return ru.Maxrss >> 10 // KiB
}

func writeReach(dir string, rows map[string]bool) error {
	var b strings.Builder
	b.WriteString(reachHeader)
	for _, row := range sortedKeys(rows) {
		b.WriteString(row + "\n")
	}
	return os.WriteFile(filepath.Join(dir, reachFile), []byte(b.String()), 0o644)
}
