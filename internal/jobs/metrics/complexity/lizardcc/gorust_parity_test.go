// pinnedGoConditionKeys/pinnedRustConditionKeys and
// TestGoRustConditionKeySetIsPinned are this PR's own invocation of the
// shared key-set-pinning mechanism cfamily's clike_parity_test.go defines
// (see TestConditionKeySetIsPinned's doc there for the deletion attack it
// closes) -- proactively wired here rather than waiting for a codex round
// to find the same gap against goConditions/rustConditions specifically.
