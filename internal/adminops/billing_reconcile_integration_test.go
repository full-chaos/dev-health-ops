// reconcileState is the audit rows the session has left, in a fixed order, with the
// random ids masked: a run's own id is random, a mismatch row names the local row.
func (db *database) reconcileState(t *testing.T) string {
	t.Helper()
	rows, err := db.conn.Query(context.Background(), `SELECT concat_ws('|', org_id::text, action, resource_type, resource_id::text, description,
		coalesce(reconciliation_status, '<null>'), coalesce(local_state::text, '<null>'), coalesce(stripe_state::text, '<null>'))
		FROM billing_audit_log ORDER BY 1`)
	if err != nil {
		t.Fatal(err)
	}
	defer rows.Close()
	var out []string
	for rows.Next() {
		var text string
		if err := rows.Scan(&text); err != nil {
			t.Fatal(err)
		}
		out = append(out, text)
	}
	if err := rows.Err(); err != nil {
		t.Fatal(err)
	}
	// resource_id sits after the org and the action: mask it for a run's own row.
	for index, line := range out {
		fields := strings.SplitN(line, "|", 5)
		if len(fields) == 5 && fields[2] == "reconciliation" {
			fields[3] = "<run>"
			out[index] = strings.Join(fields, "|")
		}
	}
	sort.Strings(out)
	raw, _ := json.Marshal(out)
	return string(raw)
}

// pythonReconcile runs the real `dev-hops billing reconcile <args>`, its Stripe
// client pointed at the fake and its listing patched to the call it was written to
// make (see the named divergences above).
func pythonReconcile(t *testing.T, db *database, extra map[string]string, args []string) (int, string, bool) {
	t.Helper()
	root, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	python := pyoracle.Resolve(t, root)
	program := "import os, sys\n" +
		"_base = os.environ.get('VENUE_STRIPE_API_BASE')\n" +
		"if _base:\n" +
		"    import stripe as _stripe\n" +
		"    _init = _stripe.StripeClient.__init__\n" +
		"    def _patched(self, *args, **kwargs):\n" +
		"        kwargs['base_addresses'] = {'api': _base}\n" +
		"        _init(self, *args, **kwargs)\n" +
		"    _stripe.StripeClient.__init__ = _patched\n" +
		"    from stripe._invoice_service import InvoiceService as _I\n" +
		"    from stripe._refund_service import RefundService as _R\n" +
		"    from stripe._subscription_service import SubscriptionService as _S\n" +
		"    def _kw(original):\n" +
		"        def patched(self, params=None, options=None, **keywords):\n" +
		"            if keywords:\n" +
		"                params = {**(params or {}), **keywords}\n" +
		"            return original(self, params, options)\n" +
		"        return patched\n" +
		"    for _svc in (_S, _I, _R):\n" +
		"        _svc.list = _kw(_svc.list)\n" +
		"from dev_health_ops import cli\n" +
		"raise SystemExit(cli.main(sys.argv[1:]))\n"
	command := exec.Command(python, append([]string{"-c", program, "billing"}, args...)...)
	pyURI := strings.Replace(db.uri, "postgres://", "postgresql://", 1)
	command.Env = append(os.Environ(), "PYTHONPATH="+filepath.Join(root, "src"), "POSTGRES_URI="+pyURI, "DATABASE_URI="+pyURI, "OTEL_ENABLED=false",
		// A --since without an offset reaches asyncpg as a naive datetime, which it reads in
		// the process zone: pin it, the verb reads such a value as UTC.
		"TZ=UTC")
	for key, value := range extra {
		command.Env = append(command.Env, key+"="+value)
	}
	var stdout, stderr bytes.Buffer
	command.Stdout, command.Stderr = &stdout, &stderr
	err = command.Run()
	code := 0
	if exit, ok := err.(*exec.ExitError); ok {
		code = exit.ExitCode()
	} else if err != nil {
		t.Fatalf("run python: %v", pyoracle.RunError(python, err, []byte(stderr.String())))
	}
	return code, stdout.String(), code == 1 && strings.Contains(stderr.String(), "Traceback")
}

func goReconcile(t *testing.T, db *database, extra map[string]string, args []string) (int, string) {
	t.Helper()
	env := map[string]string{"MIGRATION_DATABASE_URI": db.uri}
	for key, value := range extra {
		env[key] = value
	}
	lookup := func(key string) (string, bool) { value, ok := env[key]; return value, ok }
	var stdout, stderr bytes.Buffer
	code := RunBillingReconcile(context.Background(), cli.Env{Args: args[1:], Lookup: lookup, Stdout: &stdout, Stderr: &stderr})
	if strings.Contains(stdout.String()+stderr.String(), "postgres://") {
		t.Fatal("the output carries the DSN")
	}
	return code, stdout.String()
}

func reconcileSession(t *testing.T, python bool) []reconcileResult {
	t.Helper()
	db := startDatabase(t)
	ctx := context.Background()
	fake := &reconcileStripe{fixtures: loadReconcileFixtures(t)}
	server := httptest.NewServer(fake)
	t.Cleanup(server.Close)
	key := "sk_" + "test_" + "oracle_fake_key"
	previous := stripeOptions
	stripeOptions = func(k string) stripeclient.Options { return stripeclient.Options{Key: k, BaseURL: server.URL} }
	t.Cleanup(func() { stripeOptions = previous })
	var out []reconcileResult
	for _, s := range reconcileScript {
		if s.seed {
			if _, err := db.conn.Exec(ctx, s.sql); err != nil {
				t.Fatalf("seed: %v", err)
			}
			out = append(out, reconcileResult{Args: []string{"<seed>"}, State: db.reconcileState(t)})
			continue
		}
		env := map[string]string{}
		if !s.noKey {
			env["STRIPE_SECRET_KEY"] = key
		}
		fake.mu.Lock()
		fake.calls = nil
		fake.failing, fake.failingLater, fake.overrides = s.failing, s.failingLater, s.overrides
		fake.mu.Unlock()
		var code int
		var stdout string
		crash := false
		if python {
			env["VENUE_STRIPE_API_BASE"] = server.URL
			code, stdout, crash = pythonReconcile(t, db, env, s.args)
		} else {
			code, stdout = goReconcile(t, db, env, s.args)
		}
		fake.mu.Lock()
		calls := append([]string(nil), fake.calls...)
		fake.mu.Unlock()
		if strings.Contains(stdout, key) {
			t.Fatalf("the Stripe key is in the output of %v", s.args)
		}
		out = append(out, reconcileResult{Args: s.args, Exit: code, Stdout: runInstant.ReplaceAllString(stdout, `"$1": "<instant>"`),
			State: db.reconcileState(t), Calls: calls, Crash: crash})
	}
	return out
}

func compareReconcile(t *testing.T, got, want []reconcileResult, wantName string) {
	t.Helper()
	if len(got) != len(want) {
		t.Fatalf("%d steps, %s has %d", len(got), wantName, len(want))
	}
	for index := range got {
		label := strings.Join(got[index].Args, " ")
		if got[index].Exit != want[index].Exit {
			t.Errorf("step %d (%s): exit %d, %s exit %d", index, label, got[index].Exit, wantName, want[index].Exit)
		}
		if want[index].Crash {
			// Python crashed: the message differs by ruling, only the exit code is compared.
			continue
		}
		if got[index].Stdout != want[index].Stdout {
			t.Errorf("step %d (%s): stdout\n%s\n%s stdout\n%s", index, label, got[index].Stdout, wantName, want[index].Stdout)
		}
		if got[index].State != want[index].State {
			t.Errorf("step %d (%s): audit rows\n%s\n%s audit rows\n%s", index, label, got[index].State, wantName, want[index].State)
		}
		if strings.Join(got[index].Calls, "\n") != strings.Join(want[index].Calls, "\n") {
			t.Errorf("step %d (%s): Stripe requests\n%s\n%s requests\n%s", index, label, strings.Join(got[index].Calls, "\n"), wantName, strings.Join(want[index].Calls, "\n"))
		}
	}
}

