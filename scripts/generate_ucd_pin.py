"""Emit the Go source pinning the character classes to the interpreter's UCD.

Only the INTERSECTION is emitted: runes Go's tables treat as letter/number/space
(or underscore) that the live interpreter treats as unassigned. That is a few
thousand code points rather than the whole Cn set, so the table stays small and
its meaning stays exact -- it is precisely the set the port must subtract.
"""

import json
import os
import re as _re
import subprocess
import sys
import tempfile
import unicodedata
from pathlib import Path

# The Go side of the intersection is a throwaway program written at run time
# rather than a checked-in module: it exists only to enumerate what Go's tables
# consider a letter, number, space or underscore, and a committed copy would be
# one more thing to keep in step with the predicates it is measuring.
_PROBE = """package main

import (
	"encoding/json"
	"os"
	"unicode"
)

func main() {
	var out []int
	for r := rune(0); r <= 0x10FFFF; r++ {
		if unicode.IsLetter(r) || unicode.IsNumber(r) || unicode.IsSpace(r) || r == '_' ||
			(r >= 0x1C && r <= 0x1F) {
			out = append(out, int(r))
		}
	}
	_ = json.NewEncoder(os.Stdout).Encode(out)
}
"""

with tempfile.TemporaryDirectory() as probe_dir:
    Path(probe_dir, "go.mod").write_text("module ucdpinprobe\n\ngo 1.24\n")
    Path(probe_dir, "main.go").write_text(_PROBE)
    go_out = subprocess.run(
        ["go", "run", "."],
        cwd=probe_dir,
        capture_output=True,
        text=True,
        # The same bounds every other Go invocation in this repo carries.
        env={**os.environ, "GOMAXPROCS": "4", "GOFLAGS": "-p=2"},
    )
if go_out.returncode != 0:
    print(go_out.stderr[:2000], file=sys.stderr)
    raise SystemExit("go probe failed")
go_class = {int(x) for x in json.loads(go_out.stdout)}

unassigned = {cp for cp in go_class if unicodedata.category(chr(cp)) == "Cn"}

ranges: list[list[int]] = []
for cp in sorted(unassigned):
    if ranges and cp == ranges[-1][1] + 1:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp])

lines = [
    "package textrefs",
    "",
    "// Code generated by tests/fixtures/generate_ucd_pin.py. DO NOT EDIT.",
    "//",
    "// The character classes are PINNED to the interpreter's UCD, not to Go's.",
    "//",
    "// Go's unicode tables are newer than CPython's, so Go treats some code",
    "// points as letters or digits that the interpreter does not know exist. The",
    "// rune-set difference is one-directional and looks harmless, but the",
    "// direction INVERTS through the boundary logic: a rune Go alone considers a",
    "// word character widens Go's word class, so a boundary that holds for Python",
    "// FAILS for Go and the whole match is lost.",
    "//",
    "//\tsee merge request<U+11DE0>!45   Python [45]      Go nil (before the pin)",
    "//\t#1<U+11DE0>                     Python key '1'   Go key '1<U+11DE0>'",
    "//",
    "// Codex round 1 found this class; the all-runes guard had asserted the",
    "// residue was Cn-only and the package doc had called it reachable, and",
    "// neither was enough because no corpus case CONTAINED such a rune.",
    "//",
    f"// Generated against CPython UCD {unicodedata.unidata_version}, "
    f"{len(unassigned)} runes in {len(ranges)} ranges.",
    "// The all-runes guard fails loudly when either side's tables move.",
    "",
    "// pythonUnassigned holds the runes Go's classes accept and the interpreter",
    "// does not know. Sorted and non-overlapping, so lookup is a binary search.",
    "var pythonUnassigned = [][2]rune{",
]
for lo, hi in ranges:
    lines.append(f"\t{{0x{lo:04X}, 0x{hi:04X}}},")
lines.append("}")
lines.append("")
lines.append(
    "// isPythonUnassigned reports whether the interpreter's UCD lacks this rune."
)
lines.append("func isPythonUnassigned(r rune) bool {")
lines.append("\tlo, hi := 0, len(pythonUnassigned)-1")
lines.append("\tfor lo <= hi {")
lines.append("\t\tmid := (lo + hi) / 2")
lines.append("\t\tswitch {")
lines.append("\t\tcase r < pythonUnassigned[mid][0]:")
lines.append("\t\t\thi = mid - 1")
lines.append("\t\tcase r > pythonUnassigned[mid][1]:")
lines.append("\t\t\tlo = mid + 1")
lines.append("\t\tdefault:")
lines.append("\t\t\treturn true")
lines.append("\t\t}")
lines.append("\t}")
lines.append("\treturn false")
lines.append("}")

# The RE2 classes, emitted as EXPLICIT ranges from the interpreter rather than
# as \p{Nd} / \p{L}\p{N}. RE2 has no class subtraction, so a pattern written with
# a Unicode property class would still consume a residue rune even though the
# predicates reject it -- the pin has to reach the regexes too, or the two halves
# of the port disagree with each other.


def _ranges(pred):
    out: list[list[int]] = []
    for cp in range(0x110000):
        if pred(chr(cp)):
            if out and cp == out[-1][1] + 1:
                out[-1][1] = cp
            else:
                out.append([cp, cp])
    return out


def _rx(rs):
    return "".join(
        f"\\x{{{lo:04X}}}" if lo == hi else f"\\x{{{lo:04X}}}-\\x{{{hi:04X}}}"
        for lo, hi in rs
    )


_digit = _ranges(lambda c: bool(_re.match(r"\d", c)))
_word = _ranges(lambda c: bool(_re.match(r"\w", c)))

lines += [
    "",
    "// pythonDigitClassRanges is Python's `\\d` as an explicit RE2 class body.",
    f"// {sum(hi - lo + 1 for lo, hi in _digit)} runes in {len(_digit)} ranges, UCD {unicodedata.unidata_version}.",
    "//",
    "// Explicit ranges rather than \\p{Nd}: RE2 has no class subtraction, so a",
    "// property class would consume a residue rune the predicates reject, and the",
    "// regex half of the port would disagree with the predicate half.",
    "const pythonDigitClassRanges = `" + _rx(_digit) + "`",
    "",
    "// pythonWordClassRanges is Python's `\\w` as an explicit RE2 class body.",
    f"// {sum(hi - lo + 1 for lo, hi in _word)} runes in {len(_word)} ranges.",
    "const pythonWordClassRanges = `" + _rx(_word) + "`",
]

out = Path("internal/jobs/workgraph/textrefs/ucdpin.go")
out.write_text("\n".join(lines) + "\n")
print(
    f"  wrote {out}: {len(unassigned)} runes, {len(ranges)} ranges, UCD {unicodedata.unidata_version}"
)
