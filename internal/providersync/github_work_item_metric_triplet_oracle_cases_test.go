func githubWorkItemMetricOracleCase(id string, input map[string]any) oracleCase {
	complete := map[string]any{
		"Day": githubWorkItemMetricOracleDay, "ComputedAt": githubWorkItemMetricOracleNow,
		"AsOf": githubWorkItemMetricOracleNow, "OrgID": githubWorkItemMetricOracleOrg,
	}
	for key, value := range input {
		complete[key] = value
	}
	return oracleCase{ID: id, Input: complete}
}

// githubWorkItemMetricFloatSweepCase is one case holding MANY independent
// groups, so a single comparison covers a wide slice of the floating-point
// input space instead of one hand-chosen point.
//
// Hand-picking timestamps cannot cover this. The Go compiler is free to
// contract `a*b + c*d`, and Python's duration and percentile arithmetic
// decompose differently from Go's; a measured sweep put the difference at
// roughly one interpolated percentile in nine, spread unpredictably across the
// input space. A case built from four pretty durations lands on an agreeing
// point most of the time and reports a pass. This one walks 24 work scopes of
// four completions each, with microsecond-precision durations and a wait
// transition inside every cycle, so the group and user percentiles, the
// duration-to-hours conversion and the flow-breakdown seconds are all compared
// at 24 independent points at once.
//
// Generated by a fixed integer PRNG so the JSON handed to Python is identical
// on every run -- a sweep that varied per run would be a flaky oracle, which is
// worse than a narrow one.
func githubWorkItemMetricFloatSweepCase() oracleCase {
	const scopes = 24
	seed := uint64(0x2545F4914F6CDD1D)
	next := func(bound uint64) uint64 {
		seed ^= seed << 13
		seed ^= seed >> 7
		seed ^= seed << 17
		return seed % bound
	}
	// Microsecond-resolution instants only: a Python datetime cannot hold
	// anything finer, so a nanosecond here would be silently truncated on one
	// side and compared against the untruncated value on the other.
	instant := func(base time.Time, micros uint64) string {
		return base.Add(time.Duration(micros) * time.Microsecond).
			UTC().Format("2006-01-02T15:04:05.000000Z")
	}
	dayStart := time.Date(2026, 8, 4, 0, 0, 0, 0, time.UTC)
	items := make([]any, 0, scopes*4)
	transitions := make([]any, 0, scopes*4)
	for scope := 0; scope < scopes; scope++ {
		scopeID := fmt.Sprintf("acme/sweep-%02d", scope)
		for index := 0; index < 4; index++ {
			id := fmt.Sprintf("gh:%s#%d", scopeID, index)
			// Completion inside the day, cycle length anywhere from minutes to
			// most of a week, so lo/hi brackets and fracs vary across scopes.
			completedMicros := 3*3600*1000000 + next(20*3600*1000000)
			cycleMicros := 60*1000000 + next(160*3600*1000000)
			completedAt := dayStart.Add(time.Duration(completedMicros) * time.Microsecond)
			startedAt := completedAt.Add(-time.Duration(cycleMicros) * time.Microsecond)
			items = append(items, githubWorkItemMetricOracleItem(id, map[string]any{
				"status": "done", "assignees": []any{"dev@example.com"},
				"project_id":   scopeID,
				"created_at":   instant(startedAt, 0-next(48*3600*1000000)-1),
				"started_at":   instant(startedAt, 0),
				"completed_at": instant(completedAt, 0),
			}))
			// One wait span strictly inside the cycle, at an awkward offset, so
			// the active/wait split is a sum of odd microsecond segments rather
			// than of whole hours.
			blockedAt := startedAt.Add(time.Duration(next(cycleMicros/3)+1) * time.Microsecond)
			resumedAt := blockedAt.Add(time.Duration(next(cycleMicros/3)+1) * time.Microsecond)
			transitions = append(transitions,
				githubWorkItemMetricOracleTransition(id, "blocked", instant(blockedAt, 0)),
				githubWorkItemMetricOracleTransition(id, "in_progress", instant(resumedAt, 0)))
		}
	}
	return githubWorkItemMetricOracleCase("float_arithmetic_sweep_across_many_groups",
		map[string]any{"WorkItems": items, "Transitions": transitions})
}

