// TestInterfaceAndTypeAliasContributeNoFunctions pins a TypeScript-specific
// behaviour lizard measures that has no C-family/GoLike-family analogue:
// an `interface` body and a `type X = ...` alias are both skipped entirely
// by TypeScriptStates (typescript.py:171-233) -- neither's method
// signatures nor arrow-typed fields are runtime functions. types_interfaces.ts.txt
// is built specifically to exercise this: only its two real function
// declarations/object-literal methods should be counted, never the
// interface's or type alias's own signatures.
func TestInterfaceAndTypeAliasContributeNoFunctions(t *testing.T) {
	doc := loadJSTSGolden(t)
	expected, ok := doc.Files["types_interfaces.ts.txt"]
	if !ok {
		t.Fatalf("golden missing types_interfaces.ts.txt -- corpus/golden drifted apart")
	}
	// Golden proof: lizard itself (not just this port) treats interface
	// method signatures and type-alias arrow types as non-functions --
	// makeGreeter's OWN two object-literal methods (greet/farewell),
	// useHandler, and withGeneric are the ONLY real functions; Greeter's
	// two interface method signatures and Handler's arrow-typed alias
	// contribute nothing, on the REAL tool's own measurement.
	if expected.FunctionsCount != 4 {
		t.Fatalf("fixture assumption drifted: lizard now reports %d functions for "+
			"types_interfaces.ts.txt, expected 4 (greet, farewell, useHandler, "+
			"withGeneric) -- update this test's expectation only after reviewing why",
			expected.FunctionsCount)
	}

	src, err := os.ReadFile(filepath.Join(jsTSCorpusDir(t), "types_interfaces.ts.txt"))
	if err != nil {
		t.Fatalf("read fixture: %v", err)
	}
	complexities, skipped, err := AnalyzeTypeScript("types_interfaces.ts", string(src))
	if err != nil {
		t.Fatalf("AnalyzeTypeScript: %v", err)
	}
	if skipped {
		t.Fatalf("AnalyzeTypeScript skipped the fixture unexpectedly")
	}
	if len(complexities) != 4 {
		t.Errorf("got %d functions, want 4 (interface/type-alias bodies must contribute none): %v",
			len(complexities), complexities)
	}
}
