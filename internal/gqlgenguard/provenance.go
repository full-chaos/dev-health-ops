// Provenance is ANCHORED, never a substring search.
//
// gqlgen writes its notices at fixed positions, in fixed shapes, and which
// shape depends on which generator wrote the file. The guard accepts exactly
// those shapes at exactly those positions. Round 1 of review found the earlier
// "does the marker appear anywhere in the first 4096 bytes" scan accepting a
// hand-written file whose comment merely QUOTED the marker -- and then
// overwriting it. A notice is evidence only where gqlgen puts it.
//
// Every shape below is typed from the gqlgen v0.17.66 source it cites, and the
// knob matrix (assertRealGenerationStaysInsideThePlan) regenerates with the real
// CLI and runs this check over every file gqlgen wrote -- so a version bump
// that moves or rewords a notice fails a test instead of refusing a real
// checkout's own generated files as hand-written.

// generatedHeaderLine is line 1 of every file gqlgen renders with
// templates.Options.GeneratedHeader set (codegen/templates/templates.go Render):
// the exec layer in both layouts (codegen/generate.go), the model file
// (plugin/modelgen/models.go) and the federation file
// (plugin/federation/federation.go). Render writes it at byte 0, followed by a
// blank line, before the package clause.
const generatedHeaderLine = "// Code generated by github.com/99designs/gqlgen, DO NOT EDIT."

// resolverNotice is one FileNotice block plugin/resolvergen writes. Render
// places a FileNotice directly after "package <name>" and one blank line, and
// the gofmt pass gqlgen runs on every file moves its lines to column 0.
type resolverNotice struct {
	name  string
	lines []string
	// versionLine, when set, is a final line whose text is fixed up to an
	// optional " version <v>" suffix (omit_gqlgen_version_in_file_notice drops
	// the suffix).
	versionLine string
}

var resolverNotices = []resolverNotice{
	{
		// plugin/resolvergen/resolver.go generatePerSchema, every per-schema file.
		name: "follow-schema resolver notice",
		lines: []string{
			"// This file will be automatically regenerated based on the schema, any resolver implementations",
			"// will be copied through when generating and any unknown code will be moved to the end.",
		},
		versionLine: "// Code generated by github.com/99designs/gqlgen",
	},
	{
		// plugin/resolvergen/resolver.go generatePerSchema, the root resolver
		// stub (written only when absent).
		name: "dependency-injection notice",
		lines: []string{
			"// This file will not be regenerated automatically.",
			"//",
			"// It serves as dependency injection for your app, add any dependencies you require here.",
		},
	},
	{
		// plugin/resolvergen/resolver.go generateSingleFile.
		name: "single-file resolver notice",
		lines: []string{
			"// THIS CODE WILL BE UPDATED WITH SCHEMA CHANGES. PREVIOUS IMPLEMENTATION FOR SCHEMA CHANGES WILL BE KEPT IN THE COMMENT SECTION. IMPLEMENTATION FOR UNCHANGED SCHEMA WILL BE KEPT.",
		},
	},
	{
		// plugin/resolvergen/resolver.go generateSingleFile with
		// resolver.preserve_resolver set.
		name: "preserved single-file resolver notice",
		lines: []string{
			"// THIS CODE IS A STARTING POINT ONLY. IT WILL NOT BE UPDATED WITH SCHEMA CHANGES.",
		},
	},
}

// markerScanBytes bounds how much of a file the provenance check reads. Every
// shape gqlgen writes ends within its first six lines; a shape that does not
// END inside the window is not accepted.
const markerScanBytes = 4096

// utf8BOM is never written by gqlgen. A file that starts with one was not
// written by it in that form.
var utf8BOM = []byte{0xef, 0xbb, 0xbf}

// provenance decides whether the file at rel -- declared by declaree -- carries
// the notice gqlgen writes for that section, at the position gqlgen writes it.
//
// It returns the accepted shape's name, or ok=false and a reason naming what
// the file has instead. The reason is for the refusal message; it never quotes
// the file's content beyond its classification.
func provenance(root *os.Root, rel string, declaree Declaree) (shape string, ok bool, reason string, err error) {
	f, err := root.Open(rel)
	if err != nil {
		return "", false, "", fmt.Errorf("open %q: %w", rel, err)
	}
	defer f.Close()
	buf := make([]byte, markerScanBytes)
	n, err := io.ReadFull(f, buf)
	if err != nil && !errors.Is(err, io.EOF) && !errors.Is(err, io.ErrUnexpectedEOF) {
		return "", false, "", fmt.Errorf("read %q: %w", rel, err)
	}
	if declaree == DeclareeFederation && path.Base(rel) == federationRequiresFile {
		// plugin/federation/federation.go renders this file with
		// GeneratedHeader false and no FileNotice, so a generated one carries
		// nothing that tells it from a hand-written one. With no evidence the
		// guard does not overwrite -- executed: a config with
		// options.explicit_requires generates it once, and the next run refuses.
		return "", false, "gqlgen writes " + federationRequiresFile + " with no provenance notice at all, so a generated one cannot be told from a hand-written one", nil
	}
	shape, ok, reason = classifyProvenance(buf[:n], declaree)
	return shape, ok, reason, nil
}

// federationRequiresFile is the fixed name plugin/federation gives the
// explicit-requires file beside the federation output.
const federationRequiresFile = "federation.requires.go"

// classifyProvenance is the pure half of provenance, over the file's first
// markerScanBytes bytes.
func classifyProvenance(head []byte, declaree Declaree) (shape string, ok bool, reason string) {
	if bytes.HasPrefix(head, utf8BOM) {
		return "", false, "it starts with a UTF-8 byte-order mark, which gqlgen never writes"
	}
	// Only lines terminated INSIDE the window are complete; a trailing partial
	// line cannot be matched against a full-line shape.
	lines := strings.Split(string(head), "\n")
	complete := lines[:len(lines)-1]
	for _, l := range complete {
		if strings.HasSuffix(l, "\r") {
			return "", false, "it uses CRLF line endings, which gqlgen never writes"
		}
	}

	switch declaree {
	case DeclareeExec, DeclareeModel, DeclareeFederation:
		if len(complete) >= 1 && complete[0] == generatedHeaderLine {
			return "generated header at line 1", true, ""
		}
		return "", false, fmt.Sprintf("line 1 is not gqlgen's generated header %q", generatedHeaderLine)
	case DeclareeResolver:
		if len(complete) < 2 || !isPackageClause(complete[0]) || complete[1] != "" {
			return "", false, "it does not open with a bare package clause and one blank line, where gqlgen's resolver notices sit"
		}
		for _, n := range resolverNotices {
			if matchNotice(complete[2:], n) {
				return n.name + " below the package clause", true, ""
			}
		}
		return "", false, "line 3 does not begin one of gqlgen's resolver notices in full"
	default:
		return "", false, fmt.Sprintf("no provenance shape is known for the %q section", declaree)
	}
}

// isPackageClause reports whether line is exactly `package <identifier>`, the
// only form templates.Render writes.
func isPackageClause(line string) bool {
	name, found := strings.CutPrefix(line, "package ")
	return found && token.IsIdentifier(name)
}

func matchNotice(lines []string, n resolverNotice) bool {
	want := len(n.lines)
	if n.versionLine != "" {
		want++
	}
	if len(lines) < want {
		return false
	}
	for i, l := range n.lines {
		if lines[i] != l {
			return false
		}
	}
	if n.versionLine == "" {
		return true
	}
	last := lines[len(n.lines)]
	if last == n.versionLine {
		return true
	}
	v, found := strings.CutPrefix(last, n.versionLine+" version ")
	return found && v != "" && !strings.ContainsAny(v, " \t")
}
