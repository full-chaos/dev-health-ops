// TestBillingReconcileMatchesTheFrozenPythonOutput runs the script against the fake
// and compares every step, the audit rows and the Stripe requests with what the
// real Python verb did (frozen; no Python needed).
func TestBillingReconcileMatchesTheFrozenPythonOutput(t *testing.T) {
	raw, err := os.ReadFile(reconcileGolden)
	if err != nil {
		t.Fatal(err)
	}
	var frozen []reconcileResult
	if err := json.Unmarshal(raw, &frozen); err != nil {
		t.Fatal(err)
	}
	compareReconcile(t, reconcileSession(t, false), frozen, "frozen Python")
	reports, mismatches, missing, requests, crashes := 0, 0, 0, 0, 0
	for _, item := range frozen {
		if strings.Contains(item.Stdout, `"subscriptions_checked"`) {
			reports++
		}
		if strings.Contains(item.Stdout, `"mismatches": [{`) {
			mismatches++
		}
		if strings.Contains(item.Stdout, `"missing_stripe": ["`) && strings.Contains(item.Stdout, `"missing_local": ["`) {
			missing++
		}
		requests += len(item.Calls)
		if item.Crash {
			crashes++
		}
	}
	if reports < 20 || mismatches < 5 || missing < 5 || requests < 60 || crashes < 3 {
		t.Fatalf("the golden has %d reports, %d with mismatches, %d with both missing lists, %d Stripe requests, %d crashes: it measures too little",
			reports, mismatches, missing, requests, crashes)
	}
}

