-- team_memberships.provider_user_id: the provider's OWN stable id of the member
-- (GitHub numeric user id, GitLab numeric user id, Linear user id, Atlassian
-- accountId). NULL = not known: a row written before this column, a row a person
-- wrote by hand, and a row of a provider that has no id to give.
--
-- It is evidence for ONE decision: a member whose login (GitHub, GitLab) or email
-- (Linear) changed is the same person. A writer that is about to open a member
-- that no open row of the team holds finds the open row of the SAME provider and
-- the SAME id under another member_id, and the open row continues: the new
-- member id takes the valid_from of the old open row and the old one is retired,
-- so a rename is not a leave plus a join.
--
-- member_id, identity_facets and raw_provider_user_id are not changed and not
-- read differently: raw_provider_user_id still holds the first identity facet (a
-- login or a qualified identity), not a provider user id.
ALTER TABLE team_memberships ADD COLUMN IF NOT EXISTS provider_user_id Nullable(String);
