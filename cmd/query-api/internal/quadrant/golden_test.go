// queryHasCohortFilter reports whether a fetchQuadrantMetric query carries
// the person-scope team-cohort filter _cohort_scope_filter builds
// (quadrant.py:378-381).
func queryHasCohortFilter(query string) bool {
	return strings.Contains(query, "AND m.team_id = {team_id:String}")
}

type fakeQueryClient struct {
	t       *testing.T
	handler func(t *testing.T, query string, bindings []dhclickhouse.Binding) (dhclickhouse.RowScanner, error)
}

func (c fakeQueryClient) Query(_ context.Context, query string, bindings []dhclickhouse.Binding) (dhclickhouse.RowScanner, error) {
	return c.handler(c.t, query, bindings)
}

func timePtr(t time.Time) *time.Time { return &t }
