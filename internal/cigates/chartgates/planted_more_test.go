package chartgates_test

import "testing"

// Planted-defect cases for the controls whose defect class a sibling case in another file also plants:
// the same defect is run against the second guard, so each guard is observed failing on its own.

func TestControlGuardsPlantedDefects(t *testing.T) {
	const workers = chartRel + "/templates/go-workers.yaml"
	const pdb = chartRel + "/templates/go-worker-pdb.yaml"
	const keda = chartRel + "/templates/go-worker-keda.yaml"
	const hooks = chartRel + "/" + riverHooksTpl
	const helpers = chartRel + "/" + helpersTpl
	const route = chartRel + "/" + routeTpl
	const values = chartRel + "/values.yaml"
	const schema = chartRel + "/values.schema.json"
	const ch = chartRel + "/templates/clickhouse.yaml"
	const web = chartRel + "/templates/web-deployment.yaml"
	const gate = "{{- if and .Values.migrations.hook.provisionRoles.enabled .Values.migrations.hook.riverMigrate.enabled .Values.migrations.hook.routeActivate.enabled }}"
	runPlanted(t, []planted{
		{"internal-listener-on-by-default", chartOnly,
			mut(values, "  internal:\n    enabled: false\n    port: 8091", "  internal:\n    enabled: true\n    port: 8091"),
			qaiInternalOffByDefault, "renders with the internal listener off"},
		{"metrics-floor-raised-above-the-floor-itself", chartOnly,
			mut(workers, "{{- if lt (int $group.terminationGracePeriodSeconds) 7260 }}", "{{- if lt (int $group.terminationGracePeriodSeconds) 8000 }}"),
			drainMetricsAtFloorRenders, "floor itself"},
		{"default-metrics-group-ships-below-the-floor", chartOnly,
			all(mut(workers, "{{- if lt (int $group.terminationGracePeriodSeconds) 7260 }}", "{{- if lt (int $group.terminationGracePeriodSeconds) 100 }}"),
				mut(values, "      terminationGracePeriodSeconds: 7260\n", "      terminationGracePeriodSeconds: 960\n")),
			drainDefaultsSatisfyFloor, "ships below its own floor"},
		{"pdb-selector-names-another-group", chartOnly,
			mut(pdb, "      dev-health.io/worker-group: {{ $group.name }}\n{{- end }}", "      dev-health.io/worker-group: other-{{ $group.name }}\n{{- end }}"),
			drainPDBSelectorMatchesDeployment, "does not match the pod template"},
		{"pdb-for-an-autoscaled-group-capped-at-one", chartOnly,
			mut(pdb, "{{- if ge $ceiling 2 }}", "{{- if or (ge $ceiling 2) $autoscaling.enabled }}"),
			drainAutoscaledToOneNoPDB, "still permits zero voluntary evictions"},
		{"pdb-for-every-singleton", chartOnly,
			mut(pdb, "{{- if ge $ceiling 2 }}", "{{- if ge $ceiling 1 }}"),
			drainDefaultsBudgetAutoscaledGroups, "exactly the four groups"},
		{"min-replicas-floor-raised-above-one", chartOnly,
			mut(keda, "{{- if lt (int $group.autoscaling.minReplicas) 1 }}", "{{- if lt (int $group.autoscaling.minReplicas) 2 }}"),
			drainMinReplicasOneRenders, "floor itself"},
		{"min-replicas-floor-applies-to-a-disabled-group", chartOnly,
			mut(workers, "  {{- if not (and $group.autoscaling $group.autoscaling.enabled) }}\n  replicas:", "  {{- if lt (int $group.autoscaling.minReplicas) 1 }}{{ fail \"minReplicas floor applied to a disabled group\" }}{{ end }}\n  {{- if not (and $group.autoscaling $group.autoscaling.enabled) }}\n  replicas:"),
			drainAutoscalingDisabledNotConstrained, "must never trip"},
		{"default-autoscaler-ships-below-the-floor", chartOnly,
			all(mut(keda, "{{- if lt (int $group.autoscaling.minReplicas) 1 }}", "{{- if false }}"),
				mut(schema, `"minReplicas": { "type": "integer", "minimum": 1 }`, `"minReplicas": { "type": "integer", "minimum": 0 }`),
				mut(values, "      autoscaling: {enabled: true, minReplicas: 1, maxReplicas: 2, queueDepthPerReplica: 10,", "      autoscaling: {enabled: true, minReplicas: 0, maxReplicas: 2, queueDepthPerReplica: 10,")),
			drainDefaultsSatisfyMinReplicasFloor, "below the chart's own floor"},
		{"route-renders-by-default", chartOnly,
			all(mut(values, "    provisionRoles:\n      enabled: false", "    provisionRoles:\n      enabled: true"),
				mut(values, "    riverMigrate:\n", "    riverMigrate:\n      enabled: true\n"),
				mut(values, "    routeActivate:\n      enabled: true\n", "    routeActivate:\n      enabled: true\n      image: \""+pinnedOperator+"\"\n")),
			routeAbsentByDefault, ""},
		{"route-gate-inverted", chartOnly,
			mut(route, gate, "{{- if and .Values.migrations.hook.provisionRoles.enabled .Values.migrations.hook.riverMigrate.enabled (not .Values.migrations.hook.routeActivate.enabled) }}"),
			routeRendersWithFullChain, "did not render"},
		{"route-renders-with-no-password-secret", chartOnly,
			mut(hooks, "{{- if and (not $poolerSecret.create) (not $poolerSecret.externalSecretName) }}\n{{- fail", "{{- if false }}\n{{- fail"),
			routeWithoutAnyPasswordSecretFails, "the error must name"},
		{"route-enabled-default-flipped", chartOnly,
			mut(values, "    routeActivate:\n      enabled: true\n", "    routeActivate:\n      enabled: false\n"),
			routeEnabledInputDomain, "Job rendered"},
		{"route-enabled-schema-rejects-booleans", chartOnly,
			mut(schema, `"enabled": {
                  "type": "boolean",
                  "description": "Gates the CHAOS-4272`, `"enabled": {
                  "type": "string",
                  "description": "Gates the CHAOS-4272`),
			routeEnabledAcceptsRealBooleans, "must render"},
		{"route-pull-policy-default-ignores-the-explicit-value", chartOnly,
			mut(route, `{{- $operatorPullPolicy := .Values.migrations.hook.routeActivate.pullPolicy | default "IfNotPresent" }}`, `{{- $operatorPullPolicy := "IfNotPresent" }}`),
			routePullPolicyDefaultInputDomain, "did not render through unmodified"},
		{"usersd-mounts-lost-without-persistence", chartOnly,
			mut(ch, "{{- if or .Values.clickhouse.persistence.enabled .Values.clickhouse.usersd .Values.clickhouse.configd }}\n          volumeMounts:", "{{- if or .Values.clickhouse.persistence.enabled .Values.clickhouse.configd }}\n          volumeMounts:"),
			usersdWithoutPersistence, "mounts without persistence"},
		{"usersd-configmap-trims-the-content", chartOnly,
			mut(ch, "  {{- toYaml (dict $name $content) | nindent 2 }}\n  {{- end }}\n{{- end }}\n{{- if .Values.clickhouse.configd }}", "  {{ $name }}: {{ $content | trim | quote }}\n  {{- end }}\n{{- end }}\n{{- if .Values.clickhouse.configd }}"),
			usersdWhitespaceAndNumericNameRoundTrip, "did not round-trip"},
		{"keda-group-renders-replicas-for-a-fixed-value", chartOnly,
			mut(workers, "  {{- if not (and $group.autoscaling $group.autoscaling.enabled) }}\n  replicas:", "  {{- if true }}\n  replicas:"),
			kedaFixedReplicasIgnoredForScaled, "renders spec.replicas"},
		{"web-local-dev-mounts-dropped", chartOnly,
			mut(web, `{{- $webVolumeMounts = concat $webVolumeMounts (.Values.web.localDevelopment.extraVolumeMounts | default (list)) }}`, `{{- $webVolumeMounts = $webVolumeMounts }}`),
			webLocalDevOnlyUnchanged, "changed shape"},
		{"chain-hooks-on-by-default", chartOnly,
			mut(hooks, "{{- if .Values.migrations.hook.provisionRoles.enabled }}", "{{- if true }}"),
			chainHooksOffByDefault, "helm template"},
		{"provisioning-accepts-an-unpinned-image", chartOnly,
			mut(helpers, `{{- if not (or $digestPinned $immutableTag $sideloadedLocal) -}}`, `{{- if false -}}`),
			chainProvisioningRefusesUnpinnedImage, "rendered"},
		{"lockstep-refuses-a-matching-commit-for-provisioning", chartOnly,
			mut(helpers, `{{- if and $queryApiTag (ne $queryApiTag $hookImageTag) -}}`, `{{- if and $queryApiTag (eq $queryApiTag $hookImageTag) -}}`),
			chainProvisioningAcceptsLockstepAndLocal, "failed"},
		{"lockstep-refuses-a-matching-commit-for-river", chartOnly,
			mut(helpers, `{{- if and $queryApiTag (ne $queryApiTag $hookImageTag) -}}`, `{{- if and $queryApiTag (eq $queryApiTag $hookImageTag) -}}`),
			chainRiverAcceptsLockstepMatch, "failed"},
		{"river-image-ignores-the-operator-default", chartOnly,
			mut(hooks, "{{- $riverImage := .Values.migrations.hook.riverMigrate.image | default .Values.migrations.hook.routeActivate.image }}", "{{- $riverImage := .Values.migrations.hook.riverMigrate.image | default \"ghcr.io/full-chaos/dev-health-go-dho@sha256:"+hex64("7")+"\" }}"),
			chainRiverDefaultsToPinnedOperator, "want the pinned operator image"},
		{"river-image-ignores-its-own-pin", chartOnly,
			mut(hooks, "{{- $riverImage := .Values.migrations.hook.riverMigrate.image | default .Values.migrations.hook.routeActivate.image }}", "{{- $riverImage := .Values.migrations.hook.routeActivate.image }}"),
			chainRiverTakesItsOwnPinnedImage, "riverMigrate.image must win"},
		{"password-secret-created-after-the-provisioning-job", chartOnly,
			mut(hooks, "    helm.sh/hook: {{ join \",\" $hookEvents }}\n    helm.sh/hook-weight: \"-5\"\n    helm.sh/hook-delete-policy: before-hook-creation,hook-succeeded\ntype: Opaque\nstringData:", "    helm.sh/hook: {{ join \",\" $hookEvents }}\n    helm.sh/hook-weight: \"9\"\n    helm.sh/hook-delete-policy: before-hook-creation,hook-succeeded\ntype: Opaque\nstringData:"),
			chainPasswordSecretAvailableToHook, "must be created before the Job"},
		{"provisioning-ignores-the-external-password-secret", chartOnly,
			mut(hooks, `{{- $provisionSecretName := ternary (printf "%s-provision-roles-secrets" (include "dev-health.fullname" .)) (toString $poolerSecret.externalSecretName) $poolerSecret.create }}`, `{{- $provisionSecretName := printf "%s-provision-roles-secrets" (include "dev-health.fullname" .) }}`),
			chainAcceptsPreCreatedExternalSecret, "does not read the operator's own Secret"},
		{"provisioning-renders-with-no-password-secret", chartOnly,
			mut(hooks, "{{- if and (not $poolerSecret.create) (not $poolerSecret.externalSecretName) }}\n{{- fail", "{{- if false }}\n{{- fail"),
			chainWithoutAnyPasswordSecretFails, "refuse to guess"},
		{"dsn-secret-gains-a-password-key", chartOnly,
			mut(hooks, "  MIGRATION_DATABASE_URI: {{ $rolesDSN | quote }}\n", "  MIGRATION_DATABASE_URI: {{ $rolesDSN | quote }}\n  RIVER_DOMAIN_DATABASE_PASSWORD: leaked\n"),
			chainDSNSecretHasNoPasswordKey, "password key"},
		{"dsn-secret-rendered-although-the-operator-owns-it", chartOnly,
			mut(hooks, "{{- if .Values.secrets.create }}\n{{- $rolesDSN := include \"dev-health.riverMigrationDSN\" . }}", "{{- if true }}\n{{- $rolesDSN := include \"dev-health.riverMigrationDSN\" . }}"),
			chainProvisioningReadsOperatorSecretDirectly, "no DSN Secret"},
		{"empty-dsn-still-renders-a-connection-key", chartOnly,
			mut(hooks, "type: Opaque\n{{- if $rolesDSN }}\nstringData:", "type: Opaque\n{{- if true }}\nstringData:"),
			chainWithoutDSNRendersEmptySecret, "no connection key"},
		{"monitor-password-key-hardcoded", chartOnly,
			mut(hooks, "                  key: {{ $monitorSecretKey | quote }}", "                  key: \"wrong\""),
			chainMonitorEnvFromSeparateSecret, "monitor password ref"},
		{"monitor-secret-name-hardcoded", chartOnly,
			mut(hooks, "                  name: {{ $monitorSecretName | quote }}", "                  name: \"fixed\""),
			chainMonitorSecretNameAndKeyAreValues, "were not honoured"},
		{"monitor-login-rendered-without-a-name", chartOnly,
			mut(hooks, "{{- if $monitorName }}\n            - name: OTEL_PG_MONITOR_DATABASE_ROLE", "{{- if true }}\n            - name: OTEL_PG_MONITOR_DATABASE_ROLE"),
			chainMonitorWithoutNameStaysOff, "no name"},
		{"lockstep-compares-digest-pins", chartOnly,
			mut(helpers, `{{- $hookImageTag := regexFind ":sha-[0-9a-f]{12}$" .image -}}`, `{{- $hookImageTag := regexFind "[0-9a-f]{12}$" .image -}}`),
			chainRiverDigestPinIsNeverCompared, "never compared"},
		{"river-job-reads-the-shared-secret-instead", chartOnly,
			mut(hooks, "                name: {{ include \"dev-health.fullname\" . }}-river-migrate-secrets\n              {{- else }}", "                name: {{ include \"dev-health.secretName\" . }}\n              {{- else }}"),
			chainWeight10JobAppliesRiverWithElevatedDSN, "elevated DSN"},
	})
}
