// `billing reconcile` (CHAOS-6893) is compared with the real `dev-hops billing
// reconcile` on one scripted session over real PostgreSQL, each plane talking to
// its own Stripe API fake. The fake answers from objects the real Stripe SDK
// (Python stripe) builds and serialises (testdata/reconcile_fixtures.json,
// generated by DHO_RECONCILE_FIXTURE_UPDATE=1 and pinned by sha256), so no
// response is hand-written JSON, and pages them two at a time so every listing
// follows its pages. Per step: exit code, stdout (the two run instants masked),
// the audit rows the run left, and (compared between the planes) every request each
// plane made of Stripe.
//
// Named divergences, each asserted rather than hidden:
//   - the Python Stripe listing is patched to take list(limit=...) as keywords
//     (VENUE_STRIPE_LIST_KWARGS, the one the route venues use): unpatched the
//     stripe-python service refuses it and the Python Stripe side is always empty
//     (CHAOS-6479), so every local row would read as missing in Stripe;
//   - a bad --org-id or --since, a missing key or an unreachable database is a
//     Python traceback (exit 1) and a message on stderr here (exit 1 too): the
//     step records both as a crash and compares only the exit code.

