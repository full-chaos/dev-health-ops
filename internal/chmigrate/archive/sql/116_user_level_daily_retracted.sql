-- A marker for the row of zeros of the two user-level daily tables
-- (CHAOS-9135).
--
-- user_metrics_daily and work_item_user_metrics_daily hold one row for each
-- (scope, person, day); the team of the person is a VALUE column, not a part of
-- the sorting key. When a recompute no longer produces a key (a person who has
-- no row on that day any more), the old row stays the newest row of its key
-- for ever, under the team ids of the time it was computed, and every people
-- page that reads the table shows it.
--
-- The other team-keyed daily tables answer this with a row of zeros that has 0
-- in every measure. Here a MEASURED row can hold 0 in every measure (a person
-- assigned only to an item that was created that day), so a row of zeros and a
-- measured row cannot be told apart by their measures. This column tells them
-- apart: 0 = a row the compute made (the default, so every stored row stays
-- what it was), 1 = the row of zeros that retracts a key. A reader takes the
-- NEWEST row of each key first and leaves the key out when that row holds 1.
--
-- This migration only ADDS a column with a default: old pods and a rollback
-- keep reading the schema they know, and every INSERT that names its columns
-- stores 0. No stored row is rewritten.
ALTER TABLE user_metrics_daily ADD COLUMN IF NOT EXISTS retracted UInt8 DEFAULT 0;
ALTER TABLE work_item_user_metrics_daily ADD COLUMN IF NOT EXISTS retracted UInt8 DEFAULT 0;
