// This file mirrors clike_parity_test.go's contract for the two readers
// this PR adds: Go and Rust. It reuses that file's oracleDoc/oracleFile/
// oracleFunction JSON shape, complexityDiff/itoa helpers, and
// sameMultiset from jvmswift_parity_test.go -- only the corpus directory,
// golden path, and per-extension dispatch differ.

func goRustGoldenPath(t *testing.T) string {
	t.Helper()
	return filepath.Join("testdata", "lizard_cc_golden_go_rust.json")
}

func goRustCorpusDir(t *testing.T) string {
	t.Helper()
	return filepath.Join("testdata", "corpus_go_rust")
}

func loadGoRustGolden(t *testing.T) oracleDoc {
	t.Helper()
	raw, err := os.ReadFile(goRustGoldenPath(t))
	if err != nil {
		t.Fatalf("read golden: %v", err)
	}
	var doc oracleDoc
	if err := json.Unmarshal(raw, &doc); err != nil {
		t.Fatalf("parse golden: %v", err)
	}
	if len(doc.Files) == 0 {
		t.Fatalf("golden describes no files; it cannot prove parity")
	}
	return doc
}

