#!/usr/bin/env python3
"""Seed the Ask Dev entitlement state and certify the acceptance provider.

The data fixture itself is generated by ``dev-hops fixtures generate`` in the
Compose launcher. This script deliberately uses only public HTTP endpoints for
authentication, feature overrides, readiness, and capability verification.

CHAOS-3219 Wave 4 (second-org + disabled-entitlement-org auth support): after
the primary org is prepared, :func:`provision_multi_org` creates two more
organizations through the same public admin API -- one with Ask Dev enabled
(the role/entitlement matrix needs a genuinely separate tenant, not just a
second membership on the primary org) and one deliberately left WITHOUT the
ask_dev/ask_dev_contextual_entrypoints overrides (the disabled-entitlement
org), then proves both with a real, org-scoped login and capability check --
including an explicit negative-control assertion that the disabled org's
capabilities report ``ask_dev: False``. A silent no-op here (org created but
never verified) would be exactly the kind of vacuous success the acceptance
gate exists to rule out.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path
from typing import Any
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

_REQUIRED_FEATURES = (
    "ask_dev",
    "ask_dev_contextual_entrypoints",
    "ask_dev_graph_routing",
)
_DEFAULT_EXPECTED_MODEL = "ask-dev-scripted-v1"
_SECOND_ORG_NAME = "Ask Dev Acceptance Second Org"
_DISABLED_ENTITLEMENT_ORG_NAME = "Ask Dev Acceptance Disabled-Entitlement Org"


class AcceptanceFailure(RuntimeError):
    """A deterministic acceptance prerequisite was not established."""


class AcceptanceApi:
    def __init__(self, base_url: str) -> None:
        self.base_url = base_url.rstrip("/")
        self.token: str | None = None

    def request(
        self,
        method: str,
        path: str,
        payload: dict[str, Any] | None = None,
    ) -> Any:
        body = None
        headers = {"Accept": "application/json"}
        if payload is not None:
            body = json.dumps(payload, separators=(",", ":")).encode()
            headers["Content-Type"] = "application/json"
        if self.token:
            headers["Authorization"] = f"Bearer {self.token}"
        request = Request(
            f"{self.base_url}{path}",
            data=body,
            headers=headers,
            method=method,
        )
        try:
            with urlopen(request, timeout=20) as response:  # noqa: S310
                response_body = response.read()
        except HTTPError as exc:
            detail = exc.read().decode(errors="replace")
            raise AcceptanceFailure(
                f"{method} {path} returned HTTP {exc.code}: {detail}"
            ) from exc
        except URLError as exc:
            raise AcceptanceFailure(f"{method} {path} failed: {exc.reason}") from exc
        if not response_body:
            return None
        try:
            return json.loads(response_body)
        except json.JSONDecodeError as exc:
            raise AcceptanceFailure(
                f"{method} {path} returned non-JSON content"
            ) from exc


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise AcceptanceFailure(message)


def _enable_features(
    api: AcceptanceApi,
    *,
    org_id: str,
    reason: str = "Ask Dev deterministic Compose acceptance",
) -> None:
    """Enable ``_REQUIRED_FEATURES`` for ``org_id``.

    Requires a superuser token already set on ``api`` (superusers bypass the
    per-org admin-membership check on the feature-overrides endpoint --
    ``_ensure_org_admin_access`` -- so this works for any org_id without a
    membership-scoped re-login).
    """
    flags = api.request("GET", "/api/v1/admin/feature-flags")
    _require(isinstance(flags, list), "feature flag response was not a list")
    flags_by_key = {item.get("key"): item for item in flags if isinstance(item, dict)}
    missing = [key for key in _REQUIRED_FEATURES if key not in flags_by_key]
    _require(not missing, f"required feature flags are missing: {', '.join(missing)}")
    disabled = [
        key
        for key in _REQUIRED_FEATURES
        if flags_by_key[key].get("is_enabled") is not True
    ]
    _require(
        not disabled,
        f"required feature flags are globally disabled: {', '.join(disabled)}",
    )

    override_path = f"/api/v1/admin/orgs/{org_id}/feature-overrides"
    overrides = api.request("GET", override_path)
    _require(isinstance(overrides, list), "feature override response was not a list")
    overrides_by_key = {
        item.get("feature_key"): item for item in overrides if isinstance(item, dict)
    }
    for key in _REQUIRED_FEATURES:
        existing = overrides_by_key.get(key)
        if existing is None:
            created = api.request(
                "POST",
                override_path,
                {
                    "feature_id": flags_by_key[key]["id"],
                    "is_enabled": True,
                    "reason": reason,
                },
            )
            _require(
                isinstance(created, dict) and created.get("is_enabled") is True,
                f"failed to enable {key} for org {org_id}",
            )
        elif existing.get("is_enabled") is not True:
            override_id = existing.get("id")
            _require(
                isinstance(override_id, str),
                f"{key} override has no id for org {org_id}",
            )
            updated = api.request(
                "PATCH",
                f"{override_path}/{override_id}",
                {
                    "is_enabled": True,
                    "reason": reason,
                },
            )
            _require(
                isinstance(updated, dict) and updated.get("is_enabled") is True,
                f"failed to enable {key} for org {org_id}",
            )


def prepare(
    api: AcceptanceApi,
    *,
    email: str,
    password: str,
    expected_model: str = _DEFAULT_EXPECTED_MODEL,
) -> str:
    login = api.request(
        "POST",
        "/api/v1/auth/login",
        {"email": email, "password": password},
    )
    _require(isinstance(login, dict), "login response was not an object")
    token = login.get("access_token")
    user = login.get("user")
    _require(isinstance(token, str) and bool(token), "login returned no access token")
    _require(isinstance(user, dict), "login returned no user")
    _require(user.get("is_superuser") is True, "acceptance user is not a superuser")
    org_id = user.get("org_id")
    _require(isinstance(org_id, str) and bool(org_id), "login returned no org_id")
    api.token = token

    _enable_features(api, org_id=org_id)

    # CHAOS-3265: platform certification moved off the org-scoped
    # /admin/ask-dev/readiness route (now a static 410 -- org admins can no
    # longer trigger or observe platform certification) onto its own
    # superuser-only Platform Admin surface. The acceptance scripted-OpenAI
    # candidate is always PLATFORM-sourced (see production_runtime's
    # acceptance gate), so bootstrap must certify it there.
    readiness = api.request("POST", "/api/v1/admin/platform/ask-dev/readiness", {})
    _require(isinstance(readiness, dict), "readiness response was not an object")
    expected_readiness = {
        "configured": True,
        "readiness": "ready",
        "model_label": expected_model,
    }
    for field, expected in expected_readiness.items():
        _require(
            readiness.get(field) == expected,
            f"readiness {field} was {readiness.get(field)!r}, expected {expected!r}",
        )
    _require(
        bool(readiness.get("readiness_checked_at")),
        "readiness did not persist a checked-at timestamp",
    )

    capabilities = api.request("GET", "/api/v1/dev/capabilities")
    _require(isinstance(capabilities, dict), "capabilities response was not an object")
    expected_capabilities = {
        "ask_dev": True,
        "ask_dev_graph_routing": True,
        "agent_context_runtime": False,
        "can_read": True,
        "can_manage": True,
        "contextual_entrypoints": True,
        "evidence_resolver": True,
        "provider_source": "platform",
        "readiness": "ready",
        "effective_model_label": expected_model,
    }
    for field, expected in expected_capabilities.items():
        _require(
            capabilities.get(field) == expected,
            f"capability {field} was {capabilities.get(field)!r}, expected {expected!r}",
        )
    return org_id


def _create_org(api: AcceptanceApi, *, name: str, owner_user_id: str) -> str:
    org = api.request(
        "POST",
        "/api/v1/admin/orgs",
        {"name": name, "owner_user_id": owner_user_id},
    )
    _require(
        isinstance(org, dict), f"org creation response for {name!r} was not an object"
    )
    org_id = org.get("id")
    _require(
        isinstance(org_id, str) and bool(org_id),
        f"org creation for {name!r} returned no id",
    )
    return org_id


def _login(
    api: AcceptanceApi, *, email: str, password: str, org_id: str | None = None
) -> dict[str, Any]:
    payload: dict[str, Any] = {"email": email, "password": password}
    if org_id is not None:
        payload["org_id"] = org_id
    login = api.request("POST", "/api/v1/auth/login", payload)
    _require(isinstance(login, dict), "login response was not an object")
    token = login.get("access_token")
    _require(isinstance(token, str) and bool(token), "login returned no access token")
    api.token = token
    return login


def provision_multi_org(
    api: AcceptanceApi,
    *,
    email: str,
    password: str,
) -> tuple[str, str]:
    """Provision a second org (Ask Dev enabled) and a disabled-entitlement
    org, and prove both with a real org-scoped login + capability check.

    Must run after :func:`prepare` (or an equivalent login) has established a
    superuser token for ``email`` on ``api`` -- ``_create_org``/
    ``_enable_features`` both need superuser admin access, which this
    re-derives explicitly rather than trusting whatever token happens to
    already be set, so this function is safe to call standalone too.
    """
    login = _login(api, email=email, password=password)
    user = login.get("user")
    _require(isinstance(user, dict), "login returned no user")
    assert isinstance(user, dict)  # narrows for mypy; _require already enforced this
    _require(user.get("is_superuser") is True, "acceptance user is not a superuser")
    superadmin_user_id = user.get("id")
    _require(
        isinstance(superadmin_user_id, str) and bool(superadmin_user_id),
        "login returned no user id",
    )
    assert isinstance(superadmin_user_id, str)  # narrows for mypy

    second_org_id = _create_org(
        api, name=_SECOND_ORG_NAME, owner_user_id=superadmin_user_id
    )
    disabled_org_id = _create_org(
        api, name=_DISABLED_ENTITLEMENT_ORG_NAME, owner_user_id=superadmin_user_id
    )

    # Second org: entitlement explicitly enabled, same as the primary org.
    _enable_features(
        api,
        org_id=second_org_id,
        reason="Ask Dev deterministic Compose acceptance (second org)",
    )
    # Disabled-entitlement org: deliberately NOT enabled. No call here is the
    # point -- this is the negative control the launcher's boot set exists to
    # prove, verified below by asserting capabilities report it disabled.

    _login(api, email=email, password=password, org_id=second_org_id)
    second_caps = api.request("GET", "/api/v1/dev/capabilities")
    _require(
        isinstance(second_caps, dict),
        "second-org capabilities response was not an object",
    )
    _require(
        second_caps.get("ask_dev") is True
        and second_caps.get("ask_dev_graph_routing") is True
        and second_caps.get("readiness") == "ready",
        f"second org {second_org_id} did not become ask_dev-ready: {second_caps!r}",
    )

    _login(api, email=email, password=password, org_id=disabled_org_id)
    disabled_caps = api.request("GET", "/api/v1/dev/capabilities")
    _require(
        isinstance(disabled_caps, dict),
        "disabled-entitlement-org capabilities response was not an object",
    )
    # Negative control: this org never received the ask_dev override, so
    # capabilities MUST report it disabled. If this ever reads True, entitlement
    # is leaking across orgs (e.g. a global-flag / cache-key bug) -- fail loud
    # rather than silently accept an org that looks provisioned but proves
    # nothing about the disabled path.
    _require(
        disabled_caps.get("ask_dev") is False,
        "disabled-entitlement org "
        f"{disabled_org_id} unexpectedly reports ask_dev capability: {disabled_caps!r}",
    )
    _require(
        disabled_caps.get("ask_dev_graph_routing") is False,
        "disabled-entitlement org "
        f"{disabled_org_id} unexpectedly reports graph capability: {disabled_caps!r}",
    )

    return second_org_id, disabled_org_id


def main() -> int:
    if os.getenv("ASK_DEV_LIVE_ACCEPTANCE") != "1":
        print("ASK_DEV_LIVE_ACCEPTANCE=1 is required", file=sys.stderr)
        return 64
    api = AcceptanceApi(
        os.getenv("ASK_DEV_ACCEPTANCE_API_URL", "http://127.0.0.1:8000")
    )
    email = os.getenv("TEST_SUPERUSER_EMAIL", "admin@devhealth.example")
    password = os.getenv("TEST_SUPERUSER_PASSWORD", "devhealth123")
    expected_model = os.getenv(
        "ASK_DEV_ACCEPTANCE_EXPECTED_MODEL", _DEFAULT_EXPECTED_MODEL
    ).strip()
    if not expected_model:
        print("ASK_DEV_ACCEPTANCE_EXPECTED_MODEL must not be empty", file=sys.stderr)
        return 64
    try:
        org_id = prepare(
            api,
            email=email,
            password=password,
            expected_model=expected_model,
        )
        second_org_id, disabled_org_id = provision_multi_org(
            api, email=email, password=password
        )
    except AcceptanceFailure as exc:
        print(f"Ask Dev acceptance preparation failed: {exc}", file=sys.stderr)
        return 1
    print(f"Ask Dev acceptance readiness established for organization {org_id}")
    print(f"Ask Dev acceptance second org (entitlement enabled): {second_org_id}")
    print(
        "Ask Dev acceptance disabled-entitlement org "
        f"(negative control verified): {disabled_org_id}"
    )
    # Machine-parseable lines for the launcher (bash cannot easily parse the
    # prose above). CHAOS-3219 Phase 2/3 lanes needing these ids for corpus
    # fixtures should read the JSON artifact via
    # ASK_DEV_ACCEPTANCE_ORG_IDS_OUTPUT rather than re-scraping stdout.
    print(f"ASK_DEV_ACCEPTANCE_SECOND_ORG_ID={second_org_id}")
    print(f"ASK_DEV_ACCEPTANCE_DISABLED_ENTITLEMENT_ORG_ID={disabled_org_id}")
    org_ids_output = os.getenv("ASK_DEV_ACCEPTANCE_ORG_IDS_OUTPUT")
    if org_ids_output:
        Path(org_ids_output).write_text(
            json.dumps(
                {
                    "schema_version": "ask_dev_acceptance_org_ids.v1",
                    "primary_org_id": org_id,
                    "second_org_id": second_org_id,
                    "disabled_entitlement_org_id": disabled_org_id,
                },
                indent=2,
            )
            + "\n",
            encoding="utf-8",
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
