// This file mirrors java_parity_test.go's contract for PHP, reusing that
// file's oracleDoc/oracleFile/oracleFunction JSON shape and
// complexityDiff/itoa helpers. Complexities are compared by DECLARATION
// ORDER, not as a multiset -- unlike every subMachine-based reader in this
// package, phpMachine (php.go) is FLAT: it never sub_states, so functions
// always close in exactly the order lizard itself reports them.

func phpGoldenPath(t *testing.T) string {
	t.Helper()
	return filepath.Join("testdata", "lizard_cc_golden_php.json")
}

func phpCorpusDir(t *testing.T) string {
	t.Helper()
	return filepath.Join("testdata", "corpus_php")
}

func loadPHPGolden(t *testing.T) oracleDoc {
	t.Helper()
	raw, err := os.ReadFile(phpGoldenPath(t))
	if err != nil {
		t.Fatalf("read golden: %v", err)
	}
	var doc oracleDoc
	if err := json.Unmarshal(raw, &doc); err != nil {
		t.Fatalf("parse golden: %v", err)
	}
	if len(doc.Files) == 0 {
		t.Fatalf("golden describes no files; it cannot prove parity")
	}
	return doc
}

func TestGoldenPinnedToLockedLizardPHP(t *testing.T) {
	golden := loadPHPGolden(t)
	locked := lockedLizardVersion(t)
	if golden.LizardVersion != locked {
		t.Fatalf("golden was generated by lizard %q but uv.lock pins %q. "+
			"Regenerate the golden under the locked version and re-review the "+
			"numbers -- a lizard upgrade can legitimately change complexity, and "+
			"that change must be seen rather than absorbed.",
			golden.LizardVersion, locked)
	}
}

// TestGoMatchesLizardGoldenPHP proves numeric equality with real lizard
// 1.23.0 for this package's PHP analyzer, including
// interface_return_type_quirk.php.txt -- a deliberately isolated fixture
// proving PHPLanguageStates' own stuck-state bug (php.go's
// stateFunctionBodyOrReturnType doc) is reproduced exactly, down to
// reporting ZERO functions for that file.
func TestGoMatchesLizardGoldenPHP(t *testing.T) {
	doc := loadPHPGolden(t)

	entries, err := os.ReadDir(phpCorpusDir(t))
	if err != nil {
		t.Fatalf("read corpus: %v", err)
	}
	seen := 0
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".txt") {
			continue
		}
		name := entry.Name()
		expected, ok := doc.Files[name]
		if !ok {
			t.Fatalf("corpus file %s has no golden entry -- regenerate the golden", name)
		}
		seen++
		realName := strings.TrimSuffix(name, ".txt")

		t.Run(name, func(t *testing.T) {
			src, err := os.ReadFile(filepath.Join(phpCorpusDir(t), name))
			if err != nil {
				t.Fatalf("read %s: %v", name, err)
			}
			complexities, skipped, err := AnalyzePHP(realName, string(src))
			if err != nil {
				t.Fatalf("lizard analysed %s but Go failed: %v", name, err)
			}
			if skipped {
				t.Fatalf("Go skipped %s but the fixture is expected to analyse", name)
			}

			if got := len(complexities); got != expected.FunctionsCount {
				t.Errorf("functions_count: got %d, lizard %d\n%s",
					got, expected.FunctionsCount, complexityDiff(complexities, expected.Functions))
			}
			total, high, veryHigh := 0, 0, 0
			for _, c := range complexities {
				total += c
				if c > 15 {
					high++
				}
				if c > 25 {
					veryHigh++
				}
			}
			if total != expected.CyclomaticTotal {
				t.Errorf("cyclomatic_total: got %d, lizard %d\n%s",
					total, expected.CyclomaticTotal, complexityDiff(complexities, expected.Functions))
			}
			if high != expected.HighComplexityFunctions {
				t.Errorf("high_complexity_functions: got %d, lizard %d", high, expected.HighComplexityFunctions)
			}
			if veryHigh != expected.VeryHighComplexityFunction {
				t.Errorf("very_high_complexity_functions: got %d, lizard %d", veryHigh, expected.VeryHighComplexityFunction)
			}

			if len(complexities) != len(expected.Functions) {
				t.Fatalf("complexity count mismatch, cannot compare by order: got %d, lizard %d",
					len(complexities), len(expected.Functions))
			}
			for i, f := range expected.Functions {
				if complexities[i] != f.Complexity {
					t.Errorf("complexities (declaration order): got %v, lizard %v (function #%d %q: got %d, lizard %d)",
						complexities, expected.Functions, i, f.Name, complexities[i], f.Complexity)
					break
				}
			}
		})
	}
	if seen == 0 {
		t.Fatalf("no corpus files found; this test proved nothing")
	}
}

