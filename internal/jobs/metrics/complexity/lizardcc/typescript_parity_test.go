// This file mirrors java_parity_test.go's contract for JavaScript/
// TypeScript, reusing clike_parity_test.go's oracleDoc/oracleFile/
// oracleFunction JSON shape, complexityDiff/itoa helpers,
// assertGoldenBytesMatchLiveOracle/assertEveryConditionExercisedByCorpus,
// and jvmswift_parity_test.go's sameMultiset -- sub_state recursion here
// (a nested arrow/method literal) can close a nested function before or
// after its enclosing one depending on where the next unrelated brace
// falls, not strictly by source position, so complexities are compared as
// a MULTISET, not declaration order, same as every other GoLikeStates-
// shaped reader in this package.

func jsTSGoldenPath(t *testing.T) string {
	t.Helper()
	return filepath.Join("testdata", "lizard_cc_golden_js_ts.json")
}

func jsTSCorpusDir(t *testing.T) string {
	t.Helper()
	return filepath.Join("testdata", "corpus_js_ts")
}

func loadJSTSGolden(t *testing.T) oracleDoc {
	t.Helper()
	raw, err := os.ReadFile(jsTSGoldenPath(t))
	if err != nil {
		t.Fatalf("read golden: %v", err)
	}
	var doc oracleDoc
	if err := json.Unmarshal(raw, &doc); err != nil {
		t.Fatalf("parse golden: %v", err)
	}
	if len(doc.Files) == 0 {
		t.Fatalf("golden describes no files; it cannot prove parity")
	}
	return doc
}

func TestGoldenPinnedToLockedLizardJSTS(t *testing.T) {
	golden := loadJSTSGolden(t)
	locked := lockedLizardVersion(t)
	if golden.LizardVersion != locked {
		t.Fatalf("golden was generated by lizard %q but uv.lock pins %q. "+
			"Regenerate the golden under the locked version and re-review the "+
			"numbers -- a lizard upgrade can legitimately change complexity, and "+
			"that change must be seen rather than absorbed.",
			golden.LizardVersion, locked)
	}
}

// analyzerForCorpusFile routes a corpus file to AnalyzeTypeScript or
// AnalyzeJavaScript by its embedded extension, matching
// compute.go's languageByExtension split for "typescript" (.ts/.tsx) vs
// "javascript" (.js/.jsx/.mjs/.cjs) -- exercising BOTH entry points against
// ONE shared golden/corpus, since both are the identical function under
// Python's inheritance (see typescript.go's AnalyzeJavaScript doc).
func analyzerForCorpusFile(realName string) func(path, source string) ([]int, bool, error) {
	if strings.HasSuffix(realName, ".js") {
		return AnalyzeJavaScript
	}
	return AnalyzeTypeScript
}

// TestGoMatchesLizardGoldenJSTS proves numeric equality with real lizard
// 1.23.0 for this package's TypeScript/JavaScript analyzer.
func TestGoMatchesLizardGoldenJSTS(t *testing.T) {
	doc := loadJSTSGolden(t)

	entries, err := os.ReadDir(jsTSCorpusDir(t))
	if err != nil {
		t.Fatalf("read corpus: %v", err)
	}
	seen := 0
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".txt") {
			continue
		}
		name := entry.Name()
		expected, ok := doc.Files[name]
		if !ok {
			t.Fatalf("corpus file %s has no golden entry -- regenerate the golden", name)
		}
		seen++
		realName := strings.TrimSuffix(name, ".txt")
		analyze := analyzerForCorpusFile(realName)

		t.Run(name, func(t *testing.T) {
			src, err := os.ReadFile(filepath.Join(jsTSCorpusDir(t), name))
			if err != nil {
				t.Fatalf("read %s: %v", name, err)
			}
			complexities, skipped, err := analyze(realName, string(src))
			if err != nil {
				t.Fatalf("lizard analysed %s but Go failed: %v", name, err)
			}
			if skipped {
				t.Fatalf("Go skipped %s but the fixture is expected to analyse", name)
			}

			if got := len(complexities); got != expected.FunctionsCount {
				t.Errorf("functions_count: got %d, lizard %d\n%s",
					got, expected.FunctionsCount, complexityDiff(complexities, expected.Functions))
			}
			total, high, veryHigh := 0, 0, 0
			for _, c := range complexities {
				total += c
				if c > 15 {
					high++
				}
				if c > 25 {
					veryHigh++
				}
			}
			if total != expected.CyclomaticTotal {
				t.Errorf("cyclomatic_total: got %d, lizard %d\n%s",
					total, expected.CyclomaticTotal, complexityDiff(complexities, expected.Functions))
			}
			if high != expected.HighComplexityFunctions {
				t.Errorf("high_complexity_functions: got %d, lizard %d", high, expected.HighComplexityFunctions)
			}
			if veryHigh != expected.VeryHighComplexityFunction {
				t.Errorf("very_high_complexity_functions: got %d, lizard %d", veryHigh, expected.VeryHighComplexityFunction)
			}

			want := make([]int, len(expected.Functions))
			for i, f := range expected.Functions {
				want[i] = f.Complexity
			}
			if !sameMultiset(complexities, want) {
				t.Errorf("complexities (multiset): got %v, lizard %v (by declaration order: %s)",
					complexities, want, complexityDiff(complexities, expected.Functions))
			}
		})
	}
	if seen == 0 {
		t.Fatalf("no corpus files found; this test proved nothing")
	}
}

