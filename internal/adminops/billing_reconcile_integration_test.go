type reconcileFixtureSet struct {
	Subscriptions []map[string]any `json:"subscriptions"`
	Invoices      []map[string]any `json:"invoices"`
	Refunds       []map[string]any `json:"refunds"`
}

func loadReconcileFixtures(t *testing.T) reconcileFixtureSet {
	t.Helper()
	raw, err := os.ReadFile(reconcileFixtures)
	if err != nil {
		t.Fatal(err)
	}
	var set reconcileFixtureSet
	if err := json.Unmarshal(raw, &set); err != nil {
		t.Fatal(err)
	}
	return set
}

// reconcileStripe is one plane's Stripe API: it records each request and answers
// the three list endpoints from the SDK-built fixtures, two objects a page. While
// failing names a resource path, that listing is refused.
type reconcileStripe struct {
	mu       sync.Mutex
	fixtures reconcileFixtureSet
	calls    []string
	failing  string
	// failingLater refuses this path's listing from its second page on: rows already
	// read are dropped with the rest, as Python drops them (the whole listing is one
	// try block).
	failingLater string
	// overrides answers the first page of a path with this raw list envelope instead
	// of the fixtures (a shape Stripe does not send: the stripe-python reader must
	// meet it the same way as the Go one).
	overrides map[string]string
}

func (f *reconcileStripe) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	f.mu.Lock()
	defer f.mu.Unlock()
	raw, _ := io.ReadAll(r.Body)
	form, _ := url.ParseQuery(string(raw))
	auth := "other-key"
	if strings.HasPrefix(r.Header.Get("Authorization"), "Bearer sk_test_") {
		auth = "fake-key"
	}
	f.calls = append(f.calls, fmt.Sprintf("%s %s | query=%s | form=%s | version=%s | auth=%s",
		r.Method, r.URL.Path, sortedPairs(r.URL.Query()), sortedPairs(form), r.Header.Get("Stripe-Version"), auth))
	w.Header().Set("Content-Type", "application/json")
	var items []map[string]any
	switch r.URL.Path {
	case "/v1/subscriptions":
		items = f.fixtures.Subscriptions
	case "/v1/invoices":
		items = f.fixtures.Invoices
	case "/v1/refunds":
		items = f.fixtures.Refunds
	default:
		w.WriteHeader(http.StatusNotFound)
		fmt.Fprint(w, `{"error": {"message": "unrouted fake call", "type": "invalid_request_error"}}`)
		return
	}
	if f.failing == r.URL.Path || (f.failingLater == r.URL.Path && r.URL.Query().Get("starting_after") != "") {
		stripeFail(w, "listing refused")
		return
	}
	if body, ok := f.overrides[r.URL.Path]; ok && r.URL.Query().Get("starting_after") == "" {
		fmt.Fprint(w, body)
		return
	}
	start := 0
	if after := r.URL.Query().Get("starting_after"); after != "" {
		for index, item := range items {
			if objectID(item) == after {
				start = index + 1
			}
		}
	}
	end := start + 2
	if end > len(items) {
		end = len(items)
	}
	data := make([]any, 0, end-start)
	for _, item := range items[start:end] {
		data = append(data, item)
	}
	_ = json.NewEncoder(w).Encode(map[string]any{"object": "list", "url": r.URL.Path, "has_more": end < len(items), "data": data})
}

// reconcileStep is one run of the verb, with the SQL to run first (a seed step has
// none of its own verb) and how the fake behaves during it.
type reconcileStep struct {
	args  []string
	noKey bool
	sql   string
	seed  bool
	// failing refuses the listing of this Stripe path for the step; failingLater
	// only from its second page on.
	failing, failingLater string
	overrides             map[string]string
}

func rs(args ...string) reconcileStep { return reconcileStep{args: args} }

func reconcileSeed(sql string) reconcileStep {
	return reconcileStep{args: []string{"reconcile"}, seed: true, sql: sql}
}

