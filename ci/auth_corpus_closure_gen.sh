#!/usr/bin/env bash
# Prints ci/auth_corpus_closure.txt (CHAOS-11670): the repo packages in the `go list -deps` closure of the roots below, one
# directory per row, sorted. A merge queue entry that touches a file in one of these directories runs the external auth corpus
# (ci/auth_corpus_queue_relevance.sh). Regenerate with: bash ci/auth_corpus_closure_gen.sh > ci/auth_corpus_closure.txt
# internal/cigates/workflows (TestAuthCorpusClosureTableMatchesGoList) fails when the table differs from this output.
# Third-party and standard-library packages are out, and so are test-only imports.
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
roots=(./internal/api/session ./internal/api/sso ./internal/api/policy ./internal/apiservice ./cmd/dho ./cmd/auth-service)
cd "${root}"
module="$(go list -m)"
printf '# CHAOS-11670: generated by ci/auth_corpus_closure_gen.sh, do not edit by hand.\n'
printf '# Repo packages in the go list -deps closure of: %s\n' "${roots[*]#./}"
go list -deps -f '{{if not .Standard}}{{with .Module}}{{if eq .Path "'"${module}"'"}}{{$.ImportPath}}{{end}}{{end}}{{end}}' "${roots[@]}" |
  sed -e "s#^${module}/##" -e '/^$/d' | LC_ALL=C sort -u
