-- A marker for the row that retires a CI/CD repository-day (cicd_metrics_daily).
--
--   cicd_metrics_daily.retracted  UInt8 DEFAULT 0
--
-- The table holds one row for each (org, repo, day) and a reader takes the newest row of a key. A recompute of a day that
-- counts no run any more (a rerun moved the run's finish day) produces no record, so the row written before the move stays
-- the newest row of its key. The cicd family will write a row over such a key with 1 here: the key, computed_at, and the
-- column default in every measure. A reader takes the NEWEST row of each key first and leaves the key out when that row
-- holds 1, so the day reads as absent, never as 0.
--
-- The column is not in the sorting key, the partition key or the version column. ADD COLUMN with a DEFAULT changes the table
-- metadata only: no part is rewritten and no mutation is queued. Every stored row reads 0, a row the compute made. A build
-- without this migration names its columns in every INSERT, so it writes 0. Every statement can run again.
ALTER TABLE cicd_metrics_daily ADD COLUMN IF NOT EXISTS retracted UInt8 DEFAULT 0;
