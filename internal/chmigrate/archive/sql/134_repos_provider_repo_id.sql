-- CHAOS-3383: a repository's own stable id at its provider.
--
--   provider_repo_id  the provider's immutable id of the repository as text (the
--                     GitLab numeric project id); '' until a provider sync that
--                     knows it writes it. repos.id is derived from the path the
--                     sync saw, and a path can be renamed, transferred or taken
--                     by a new project; this column is what tells a later sync
--                     that a row under another path is the same repository.
--
-- Additive, no data mutation, no backfill: the next GitLab repository sync
-- writes the id. Every writer of repos carries the held value forward when its
-- row states none (stored-version contract; census
-- TestEveryReposWriterCarriesTheProviderRepoID).
ALTER TABLE repos ADD COLUMN IF NOT EXISTS provider_repo_id String DEFAULT '';
